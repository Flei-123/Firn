"""tools/ucd/expand.py -- writes tools/ucd/ucd_real.fi.

WHAT THIS SCRIPT DOES **NOT** DO: it does not read a single Unicode
category. It knows nothing about the UCD. It repeats ONE `comptime` block
eight times with a different octet window each, and it picks the eight
window boundaries so that each of them lies on a line start and never
between a `<..., First>` line and its `<..., Last>` partner.

WHY EIGHT BLOCKS AND NOT ONE: `compiler/src/comptime.rs` allows
`MAX_STEPS = 2_000_000` executed statements per `comptime` block (SPEC
14.1.comptime, "a comptime must not hang the compiler"). Measured on
2026-08-23 with `tools/ucd/probe2.fi`: a window of 400,065 octets goes
through, 500,000 aborts -- the parse loop costs about five steps per octet.
`UnicodeData.txt` has 2,198,209 octets and therefore does not fit into one
block. A fresh interpreter is built per block (`run_blocks_out`), so the
budget applies per block; eight windows of ~275 KB each stay well inside it.

The whole parsing of the UCD -- hexadecimal code point, the name field, the
general category, the First/Last range convention, and the coalescing of
neighbouring code points with the same category into ranges -- happens
inside the `comptime` blocks, i.e. **in Firn, in the compiler**. This
script only supplies eight numbers.

Usage:
    python3 tools/ucd/expand.py           # write ucd_real.fi
    python3 tools/ucd/expand.py --check   # only check that it is up to date
"""
import bisect
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
UCD = os.path.join(HERE, "UnicodeData.txt")
OUT = os.path.join(HERE, "ucd_real.fi")
CHUNKS = 8

# --- the eight windows -------------------------------------------------


def boundaries(data):
    n = len(data)
    starts = []
    forbidden = set()
    off = 0
    for line in data.split(b"\n"):
        starts.append(off)
        fields = line.split(b";")
        if len(fields) > 2 and fields[1].endswith(b", First>"):
            # the NEXT line is the matching `, Last>` -- never split here
            forbidden.add(off + len(line) + 1)
        off += len(line) + 1
    bounds = [0]
    for k in range(1, CHUNKS):
        target = n * k // CHUNKS
        idx = bisect.bisect_left(starts, target)
        while starts[idx] in forbidden:
            idx += 1
        bounds.append(starts[idx])
    bounds.append(n)
    return bounds


# --- the text ----------------------------------------------------------

HEAD = '''// expect_exit: 0
// tools/ucd/ucd_real.fi -- ACCEPTANCE ITEM 6, against the REAL UCD.
//
// GENERATED by tools/ucd/expand.py -- do not edit by hand, edit the script.
// The script contributes eight octet offsets and nothing else; every line of
// Unicode data below is read and interpreted by the COMPILER, at compile
// time, out of `comptime` blocks.
//
// What happens here:
//
//   * `file_size`/`file_byte` (SPEC 14.1.comptime, round 14) read the real
//     `UnicodeData.txt` of the Unicode Character Database, %(bytes)d octets,
//     %(lines)d lines, sha256 in tools/ucd/UnicodeData.sha256.
//   * the `comptime` blocks parse it: field 0 = code point (hexadecimal),
//     field 1 = name, field 2 = general category. The `<..., First>` /
//     `<..., Last>` convention of the UCD is resolved into a real range.
//   * neighbouring code points with the SAME category are coalesced into one
//     range, and every range is emitted as one Firn statement `d(lo, hi, cat)`
//     plus one arm of a lookup function. The category is encoded as
//     `first letter * 256 + second letter`, e.g. `Lu` = 76*256+117 = 19573.
//   * `emit_raw`/`emit_number` (round 13) write that Firn source text, which
//     the SAME compilation run lexes, parses, type-checks and compiles.
//
// The proof is not that it compiles: `ucd_dump()` prints the whole generated
// table, and `tools/ucd/verify.py` holds it against a parser of its own over
// ALL 1,114,112 code points. `tools/ucd/run.sh` drives both and carries a
// counter-check that has to strike.
//
// SECURITY (SPEC 14.1.comptime): the path is relative to the root source
// file, without `..` and without a leading `/` -- which is why the data file
// lies next to this one.

// ---------------------------------------------------------------- output

// Prints "lo hi Xy\\n" -- one line per range of the generated table.
fn d(lo: i64, hi: i64, cat: i64) {
    var buf: [u8; 64] = [0; 64]
    var tmp: [u8; 24] = [0; 24]
    var n: usize = 0
    var m: usize = 0
    var i: usize = 0

    var x: i64 = lo
    if x == 0 {
        tmp[0] = 48
        m = 1
    }
    while x > 0 {
        tmp[m] = (x %% 10) as u8 + 48
        x = x / 10
        m = m + 1
    }
    i = 0
    while i < m {
        buf[n] = tmp[m - 1 - i]
        n = n + 1
        i = i + 1
    }
    buf[n] = 32
    n = n + 1

    m = 0
    x = hi
    if x == 0 {
        tmp[0] = 48
        m = 1
    }
    while x > 0 {
        tmp[m] = (x %% 10) as u8 + 48
        x = x / 10
        m = m + 1
    }
    i = 0
    while i < m {
        buf[n] = tmp[m - 1 - i]
        n = n + 1
        i = i + 1
    }
    buf[n] = 32
    n = n + 1

    buf[n] = (cat / 256) as u8
    n = n + 1
    buf[n] = (cat %% 256) as u8
    n = n + 1
    buf[n] = 10
    n = n + 1
    syscall(1, 1, &buf[0], n as i64)
}
'''

BLOCK = '''
// ------------------------------------------------- block %(k)d: octets %(start)d .. %(end)d
comptime {
    let n: i64 = file_size("UnicodeData.txt")
    var i: i64 = %(start)d
    var seen: i64 = 0
    var ranges: i64 = 0
    var lo: i64 = 0 - 1
    var hi: i64 = 0 - 1
    var cat: i64 = 0
    var pending: i64 = 0 - 1
    emit_raw("fn ucd_dump_%(k)d() {\\n")
    while i < n {
        if i >= %(end)d { break }
        // ---- field 0: the code point, hexadecimal
        var cp: i64 = 0
        var digits: i64 = 0
        while i < n {
            let c: i64 = file_byte("UnicodeData.txt", i)
            var dg: i64 = 0 - 1
            if c >= 48 { if c <= 57 { dg = c - 48 } }
            if c >= 65 { if c <= 70 { dg = c - 55 } }
            if c >= 97 { if c <= 102 { dg = c - 87 } }
            if dg < 0 { break }
            cp = cp * 16 + dg
            digits = digits + 1
            i = i + 1
        }
        // ---- field 1: the name (only its last octets matter)
        i = i + 1
        let name_start: i64 = i
        while i < n {
            if file_byte("UnicodeData.txt", i) == 59 { break }
            i = i + 1
        }
        let name_end: i64 = i
        i = i + 1
        // ---- field 2: the general category, two letters
        let a: i64 = file_byte("UnicodeData.txt", i)
        let b: i64 = file_byte("UnicodeData.txt", i + 1)
        let this_cat: i64 = a * 256 + b
        // ---- the rest of the line
        while i < n {
            if file_byte("UnicodeData.txt", i) == 10 { break }
            i = i + 1
        }
        i = i + 1
        if digits > 0 {
            seen = seen + 1
            // `, First>` (8 octets) and `, Last>` (7 octets) -- the range
            // convention of the UCD, recognised in the file itself.
            var is_first: i64 = 0
            var is_last: i64 = 0
            if name_end - name_start >= 8 {
                if file_byte("UnicodeData.txt", name_end - 8) == 44 {
                    if file_byte("UnicodeData.txt", name_end - 6) == 70 {
                        if file_byte("UnicodeData.txt", name_end - 1) == 62 {
                            is_first = 1
                        }
                    }
                }
            }
            if name_end - name_start >= 7 {
                if file_byte("UnicodeData.txt", name_end - 7) == 44 {
                    if file_byte("UnicodeData.txt", name_end - 5) == 76 {
                        if file_byte("UnicodeData.txt", name_end - 1) == 62 {
                            is_last = 1
                        }
                    }
                }
            }
            var entry_lo: i64 = cp
            var entry_hi: i64 = cp
            var hold: i64 = 0
            if is_first == 1 {
                pending = cp
                hold = 1
            }
            if is_last == 1 {
                entry_lo = pending
                entry_hi = cp
                pending = 0 - 1
            }
            if hold == 0 {
                var merged: i64 = 0
                if lo >= 0 {
                    if cat == this_cat {
                        if entry_lo == hi + 1 {
                            hi = entry_hi
                            merged = 1
                        }
                    }
                }
                if merged == 0 {
                    if lo >= 0 {
                        emit_raw("    d(")
                        emit_number(lo)
                        emit_raw(", ")
                        emit_number(hi)
                        emit_raw(", ")
                        emit_number(cat)
                        emit_raw(")\\n")
                        ranges = ranges + 1
                    }
                    lo = entry_lo
                    hi = entry_hi
                    cat = this_cat
                }
            }
        }
    }
    if lo >= 0 {
        emit_raw("    d(")
        emit_number(lo)
        emit_raw(", ")
        emit_number(hi)
        emit_raw(", ")
        emit_number(cat)
        emit_raw(")\\n")
        ranges = ranges + 1
    }
    emit_raw("}\\n")
    emit_raw("const UCD_RANGES_%(k)d: i64 = ")
    emit_number(ranges)
    emit_raw("\\nconst UCD_LINES_%(k)d: i64 = ")
    emit_number(seen)
    emit_raw("\\nconst UCD_END_%(k)d: i64 = ")
    emit_number(i)
    emit_raw("\\n")
}
'''

