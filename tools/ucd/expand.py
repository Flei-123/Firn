TAIL = '''
// ------------------------------------------------------------- the roof
comptime {
    emit_raw("fn ucd_dump() {\\n")
    for k in 0..%(chunks)d {
        emit_raw("    ucd_dump_")
        emit_number(k)
        emit_raw("()\\n")
    }
    emit_raw("}\\n")
    emit_raw("fn ucd_category(c: i64) -> i64 {\\n")
    for k in 0..%(chunks)d {
        emit_raw("    let r")
        emit_number(k)
        emit_raw(": i64 = ucd_cat_")
        emit_number(k)
        emit_raw("(c)\\n    if r")
        emit_number(k)
        emit_raw(" >= 0 { return r")
        emit_number(k)
        emit_raw(" }\\n")
    }
    // everything not in the UCD is Cn -- unassigned -- and gets 0.
    emit_raw("    return 0\\n}\\n")
}

fn main() -> i32 {
    // Spot checks against the Unicode standard, written out by hand.
    // `Lu` = 76*256+117 = 19573, `Ll` = 19564, `Nd` = 20068, `Zs` = 23155,
    // `Lo` = 19567, `Cs` = 17267, `So` = 21359, `Co` = 17263, `Zl` = 23148,
    // `Mn` = 19822. 0 means: not in the UCD, i.e. Cn.
    if ucd_category(65) != 19573 { return 1 }
    if ucd_category(97) != 19564 { return 2 }
    if ucd_category(48) != 20068 { return 3 }
    if ucd_category(32) != 23155 { return 4 }
    if ucd_category(769) != 19822 { return 5 }
    if ucd_category(8232) != 23148 { return 6 }
    // 0xD800 -- a surrogate, category Cs
    if ucd_category(55296) != 17267 { return 7 }
    // 0x4E00 and 0xAC00 -- both come out of a `First>`/`Last>` range
    if ucd_category(19968) != 19567 { return 8 }
    if ucd_category(44032) != 19567 { return 9 }
    // 0x20000 -- CJK extension B, also a range
    if ucd_category(131072) != 19567 { return 10 }
    // 0x1F600 -- an emoji, So
    if ucd_category(128512) != 21359 { return 11 }
    // 0x10FFFD -- private use of plane 16, the last line of a range
    if ucd_category(1114109) != 17263 { return 12 }
    // 0x0378 and 0x10FFFF are unassigned
    if ucd_category(888) != 0 { return 13 }
    if ucd_category(1114111) != 0 { return 14 }
    // the whole file was walked through, not a part of it
    if UCD_END_%(last)d < %(bytes)d { return 15 }
    // every line of the file was seen -- summed over the eight blocks
    if %(lines_total)s != %(records)d { return 16 }
    if %(ranges_total)s < 1 { return 17 }
    ucd_dump()
    return 0
}
'''


def build():
    data = open(UCD, "rb").read()
    bounds = boundaries(data)
    lines = data.count(b"\n")
    records = 0
    for line in data.split(b"\n"):
        if len(line.split(b";")) > 2:
            records += 1
    text = HEAD % {"bytes": len(data), "lines": lines}
    for k in range(CHUNKS):
        text += BLOCK % {"k": k, "start": bounds[k], "end": bounds[k + 1]}
    for k in range(CHUNKS):
        text += LOOKUP % {"k": k, "start": bounds[k], "end": bounds[k + 1]}
    text += TAIL % {
        "chunks": CHUNKS,
        "last": CHUNKS - 1,
        "bytes": len(data),
        "records": records,
        "lines_total": " + ".join("UCD_LINES_%d" % k for k in range(CHUNKS)),
        "ranges_total": " + ".join("UCD_RANGES_%d" % k for k in range(CHUNKS)),
    }
    return text


def main():
    text = build()
    if "--check" in sys.argv:
        have = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if have != text:
            print("ucd_real.fi is NOT up to date -- run tools/ucd/expand.py")
            return 1
        print("ucd_real.fi is up to date (%d octets, sha256 %s)"
              % (len(text), hashlib.sha256(text.encode()).hexdigest()[:16]))
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("written: %s (%d octets, %d lines)"
          % (OUT, len(text), text.count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
