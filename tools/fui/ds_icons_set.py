import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
LIB = os.path.join(ROOT, "lib")
FUI = os.path.join(LIB, "fui")
SET_NAME = "ds_icons_set.fi"
SIZES = (16, 20, 24)
IMPORT = re.compile(r"^import\s+([A-Za-z0-9_.]+)\s*$", re.M)
NAME_REF = re.compile(r"ds_icons_names\.([A-Z][A-Z0-9_]*)")
STRING_REF = re.compile(r"ds_icons\.(?:draw|find)\([^\"\n)]*\"([a-z][a-z0-9_]*)\"")
IGNORED = {"COUNT"}


def read(path):
    with open(path, encoding="utf-8", errors="replace") as fh:
        return fh.read()


def resolve(app_dir, module):
    if module.startswith("fui."):
        path = os.path.join(FUI, module[4:] + ".fi")
    elif "." not in module:
        path = os.path.join(app_dir, module + ".fi")
    else:
        return None
    return path if os.path.exists(path) else None


def closure(app_dir):
    seen = {}
    todo = [os.path.join(app_dir, "main.fi")]
    while todo:
        path = todo.pop()
        if path in seen or not os.path.exists(path):
            continue
        src = read(path)
        seen[path] = src
        for module in IMPORT.findall(src):
            nxt = resolve(app_dir, module)
            if nxt and os.path.basename(nxt) != SET_NAME:
                todo.append(nxt)
    return seen


def catalog():
    names = re.findall(r'if id == (\d+) \{ return "([^"]*)" \}', read(os.path.join(FUI, "ds_icons_names.fi")))
    return {n: int(i) for i, n in names}


def core_names():
    m = re.search(r"^CORE\s*=\s*\(([^)]*)\)", read(os.path.join(ROOT, "tools", "fui", "ds_icons.py")), re.M)
    return set(re.findall(r"[a-z0-9_]+", m.group(1)))


def used_names(app_dir):
    found = set()
    for src in closure(app_dir).values():
        for line in src.split("\n"):
            code = line.split("//", 1)[0]
            for m in NAME_REF.finditer(code):
                if m.group(1) not in IGNORED:
                    found.add(m.group(1).lower())
            for m in STRING_REF.finditer(code):
                found.add(m.group(1))
    return found


def variants(size):
    text = read(os.path.join(FUI, "ds_icons_data%d.fi" % size))
    return set(re.findall(r"^fn ([rf]_[a-z0-9_]+)\(\)", text, re.M))


def call(size, style, name, have):
    fn = "%s_%s" % (style, name)
    return "ds_icons_data%d.%s()" % (size, fn) if fn in have[size] else None


def render(app_dir):
    ids = catalog()
    core = core_names()
    wanted = sorted((ids[n], n) for n in used_names(app_dir) if n in ids and n not in core)
    have = {size: variants(size) for size in SIZES}
    o = "// SPDX-License-Identifier: MPL-2.0\n// GENERATED by tools/fui/ds_icons_set.py. Do not edit.\n"
    o += "import fui.ds_icons\n" + "".join("import fui.ds_icons_data%d\n" % s for s in SIZES)
    o += "\nexport { install }\n\nfn look(id: i64, grade: i64, filled: bool) -> str {\n"
    for icon_id, name in wanted:
        o += "    if id == %d {\n" % icon_id
        for grade, size in enumerate(SIZES):
            reg, fil = call(size, "r", name, have), call(size, "f", name, have)
            o += "        if grade == %d {\n" % grade if grade < 2 else ""
            ind = "            " if grade < 2 else "        "
            if fil:
                o += "%sif filled { return %s }\n" % (ind, fil)
            o += '%sreturn %s\n' % (ind, reg or '""')
            o += "        }\n" if grade < 2 else ""
        o += "    }\n"
    o += '    return ""\n}\n\nfn install() {\n    ds_icons.set_full(look)\n}\n'
    return o


def main():
    check = "--check" in sys.argv
    dirs = [a for a in sys.argv[1:] if not a.startswith("--")]
    bad = 0
    for app_dir in dirs:
        app_dir = os.path.abspath(app_dir)
        target = os.path.join(app_dir, SET_NAME)
        text = render(app_dir)
        if check:
            if not os.path.exists(target) or read(target) != text:
                sys.stderr.write("stale icon set: %s\n" % target)
                bad = 1
        else:
            with open(target, "w", encoding="utf-8") as fh:
                fh.write(text)
    sys.exit(bad)


if __name__ == "__main__":
    main()
