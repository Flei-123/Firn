import itertools
import barcode.charsets.code128 as c
import barcode.charsets.code39 as d


def widths(bits):
    return "".join(str(len(list(g))) for _, g in itertools.groupby(bits))


w128 = "".join(widths(p) for p in c.CODES)
stop = widths(c.STOP + "11")
ref = "".join(d.MAP.keys()) + "*"
pats = ""
for k, (idx, bits) in d.MAP.items():
    pats += "".join("1" if len(list(g)) == 3 else "0" for _, g in itertools.groupby(bits))
pats_edge = "".join("1" if len(list(g)) == 3 else "0" for _, g in itertools.groupby(d.EDGE))
print("// SPDX-License-Identifier: MPL-2.0")
print("// lib/barcode/bctab.fi -- barcode.bctab: Code 128 and Code 39 pattern tables (generated by tools/barcode/gen_tabs.py).")
print("")
print("export { CODE128_WIDTHS, CODE128_STOP, CODE39_CHARS, CODE39_WIDE }")
print("")
print('const CODE128_WIDTHS: str = "%s"' % w128)
print('const CODE128_STOP: str = "%s"' % stop)
print('const CODE39_CHARS: str = "%s"' % ref)
print('const CODE39_WIDE: str = "%s"' % (pats + pats_edge))
