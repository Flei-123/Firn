#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."
export GCNAMES_TARGET="${1:-lib/firnc1/gcnames.fi}"
python3 - <<'PYEOF'
import os
target = os.environ.get('GCNAMES_TARGET', 'lib/firnc1/gcnames.fi')
names = [l.strip() for l in open('lib/gc/runtime_names.txt') if l.strip()]
out = []
out.append('// SPDX-License-Identifier: MPL-2.0')
out.append('// lib/firnc1/gcnames.fi -- GENERATED by tools/gen_gcnames.sh from')
out.append('// lib/gc/runtime_names.txt. DO NOT EDIT BY HAND.')
out.append('import rt')
out.append('')
out.append('export { gcnames_is_runtime }')
out.append('')
out.append('fn gcnames_is_runtime(p: u64, n: usize) -> bool {')
for i, name in enumerate(names):
    out.append('    var n%d: [u8; %d] = "%s"' % (i, len(name), name))
for i, name in enumerate(names):
    out.append('    if n == %d && rt.mem_eq(p, (&n%d[0]) as u64, %d) { return true }' % (len(name), i, len(name)))
out.append('    return false')
out.append('}')
open(target, 'w').write('\n'.join(out) + '\n')
print(target + ':', len(names), 'names')
PYEOF
