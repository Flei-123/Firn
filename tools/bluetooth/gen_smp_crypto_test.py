import random
import sys
from bumble import crypto

rng = random.Random(20261025)


def rb(n):
    return bytes(rng.randrange(256) for _ in range(n))


out = []
w = out.append
w("// expect_exit: 0")
w("// SPDX-License-Identifier: MPL-2.0")
w("// GENERATED by tools/bluetooth/gen_smp_crypto_test.py (reference: bumble.crypto); do not edit.")
w("import std.rt")
w("import std.testkit")
w("import bluetooth.bt_hex")
w("import bluetooth.bt_cmac")
w("import bluetooth.bt_smp_crypto")
w("")
w("fn put(b: *mut rt.Buf, hex: str) {")
w("    rt.buf_clear(b)")
w("    testkit.check(bt_hex.hex_parse(hex, b), \"hex parses\")")
w("}")
w("")
w("fn same(got: u64, n: usize, want: str, what: str) {")
w("    var h: rt.Buf = rt.buf_new()")
w("    bt_hex.hex_put(&h, got, n)")
w("    testkit.check(rt.buf_str(&h) == want, what)")
w("    rt.buf_free(&h)")
w("}")
w("")

cases = []

def hx(x):
    return bytes(x).hex()

for n in [0, 1, 15, 16, 17, 31, 32, 33, 40, 64, 65, 100]:
    key = rb(16)
    msg = rb(n)
    cases.append(("cmac", key, msg, crypto.aes_cmac(msg, key)))
cases.append(("cmac", bytes.fromhex("2b7e151628aed2a6abf7158809cf4f3c"), bytes.fromhex("6bc1bee22e409f96e93d7e117393172a"), None))
cases[-1] = (cases[-1][0], cases[-1][1], cases[-1][2], crypto.aes_cmac(cases[-1][2], cases[-1][1]))

w("fn main() -> i32 {")
w("    if !gc_init() { return 1 }")
w("    var a: rt.Buf = rt.buf_new()")
w("    var b: rt.Buf = rt.buf_new()")
w("    var c: rt.Buf = rt.buf_new()")
w("    var d: rt.Buf = rt.buf_new()")
w("    var e: rt.Buf = rt.buf_new()")
w("    var f: rt.Buf = rt.buf_new()")
w("    var g: rt.Buf = rt.buf_new()")
w("    var o: [u8; 32] = [0; 32]")
w("    var o2: [u8; 32] = [0; 32]")
w("    let op: u64 = (&o[0]) as u64")
w("    let op2: u64 = (&o2[0]) as u64")
for kind, key, msg, mac in cases:
    w(f"    put(&a, \"{hx(key)}\")")
    w(f"    put(&b, \"{hx(msg)}\")")
    w(f"    bt_cmac.aes_cmac(rt.buf_ptr(&a), rt.buf_ptr(&b), {len(msg)}, op)")
    w(f"    same(op, 16, \"{hx(mac)}\", \"aes_cmac len {len(msg)}\")")

for i in range(12):
    k, r, preq, pres, ia, ra = rb(16), rb(16), rb(7), rb(7), rb(6), rb(6)
    iat, rat = rng.randrange(2), rng.randrange(2)
    want = crypto.c1(k, r, preq, pres, iat, rat, ia, ra)
    w(f"    put(&a, \"{hx(k)}\")")
    w(f"    put(&b, \"{hx(r)}\")")
    w(f"    put(&c, \"{hx(preq)}\")")
    w(f"    put(&d, \"{hx(pres)}\")")
    w(f"    put(&e, \"{hx(ia)}\")")
    w(f"    put(&f, \"{hx(ra)}\")")
    w(f"    bt_smp_crypto.c1(rt.buf_ptr(&a), rt.buf_ptr(&b), rt.buf_ptr(&c), rt.buf_ptr(&d), {iat}, {rat}, rt.buf_ptr(&e), rt.buf_ptr(&f), op)")
    w(f"    same(op, 16, \"{hx(want)}\", \"c1 case {i}\")")
    k, r1, r2 = rb(16), rb(16), rb(16)
    want = crypto.s1(k, r1, r2)
    w(f"    put(&a, \"{hx(k)}\")")
    w(f"    put(&b, \"{hx(r1)}\")")
    w(f"    put(&c, \"{hx(r2)}\")")
    w(f"    bt_smp_crypto.s1(rt.buf_ptr(&a), rt.buf_ptr(&b), rt.buf_ptr(&c), op)")
    w(f"    same(op, 16, \"{hx(want)}\", \"s1 case {i}\")")
    k, rr = rb(16), rb(3)
    want = crypto.ah(k, rr)
    w(f"    put(&a, \"{hx(k)}\")")
    w(f"    put(&b, \"{hx(rr)}\")")
    w(f"    bt_smp_crypto.ah(rt.buf_ptr(&a), rt.buf_ptr(&b), op)")
    w(f"    same(op, 3, \"{hx(want)}\", \"ah case {i}\")")
    u, v, x, z = rb(32), rb(32), rb(16), rng.randrange(256)
    want = crypto.f4(u, v, x, bytes([z]))
    w(f"    put(&a, \"{hx(u)}\")")
    w(f"    put(&b, \"{hx(v)}\")")
    w(f"    put(&c, \"{hx(x)}\")")
    w(f"    bt_smp_crypto.f4(rt.buf_ptr(&a), rt.buf_ptr(&b), rt.buf_ptr(&c), {z}, op)")
    w(f"    same(op, 16, \"{hx(want)}\", \"f4 case {i}\")")
    ww, n1, n2, a1, a2 = rb(32), rb(16), rb(16), rb(7), rb(7)
    mk, ltk = crypto.f5(ww, n1, n2, a1, a2)
    w(f"    put(&a, \"{hx(ww)}\")")
    w(f"    put(&b, \"{hx(n1)}\")")
    w(f"    put(&c, \"{hx(n2)}\")")
    w(f"    put(&d, \"{hx(a1)}\")")
    w(f"    put(&e, \"{hx(a2)}\")")
    w(f"    bt_smp_crypto.f5(rt.buf_ptr(&a), rt.buf_ptr(&b), rt.buf_ptr(&c), rt.buf_ptr(&d), rt.buf_ptr(&e), op, op2)")
    w(f"    same(op, 16, \"{hx(mk)}\", \"f5 mackey case {i}\")")
    w(f"    same(op2, 16, \"{hx(ltk)}\", \"f5 ltk case {i}\")")
    ww, n1, n2, rr, io, a1, a2 = rb(16), rb(16), rb(16), rb(16), rb(3), rb(7), rb(7)
    want = crypto.f6(ww, n1, n2, rr, io, a1, a2)
    w(f"    put(&a, \"{hx(ww)}\")")
    w(f"    put(&b, \"{hx(n1)}\")")
    w(f"    put(&c, \"{hx(n2)}\")")
    w(f"    put(&d, \"{hx(rr)}\")")
    w(f"    put(&e, \"{hx(io)}\")")
    w(f"    put(&f, \"{hx(a1)}\")")
    w(f"    put(&g, \"{hx(a2)}\")")
    w(f"    bt_smp_crypto.f6(rt.buf_ptr(&a), rt.buf_ptr(&b), rt.buf_ptr(&c), rt.buf_ptr(&d), rt.buf_ptr(&e), rt.buf_ptr(&f), rt.buf_ptr(&g), op)")
    w(f"    same(op, 16, \"{hx(want)}\", \"f6 case {i}\")")
    u, v, x, y = rb(32), rb(32), rb(16), rb(16)
    want = crypto.g2(u, v, x, y)
    w(f"    put(&a, \"{hx(u)}\")")
    w(f"    put(&b, \"{hx(v)}\")")
    w(f"    put(&c, \"{hx(x)}\")")
    w(f"    put(&d, \"{hx(y)}\")")
    w(f"    testkit.check(bt_smp_crypto.g2(rt.buf_ptr(&a), rt.buf_ptr(&b), rt.buf_ptr(&c), rt.buf_ptr(&d)) == {want}, \"g2 case {i}\")")
    ww, kid = rb(16), rb(4)
    want = crypto.h6(ww, kid)
    w(f"    put(&a, \"{hx(ww)}\")")
    w(f"    put(&b, \"{hx(kid)}\")")
    w(f"    bt_smp_crypto.h6(rt.buf_ptr(&a), rt.buf_ptr(&b), op)")
    w(f"    same(op, 16, \"{hx(want)}\", \"h6 case {i}\")")
    salt = rb(16)
    want = crypto.h7(salt, ww)
    w(f"    put(&b, \"{hx(salt)}\")")
    w(f"    bt_smp_crypto.h7(rt.buf_ptr(&b), rt.buf_ptr(&a), op)")
    w(f"    same(op, 16, \"{hx(want)}\", \"h7 case {i}\")")

w("    return testkit.finish()")
w("}")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
