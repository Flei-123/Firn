import sys
from bumble import hci

A = hci.Address
PUB = A.PUBLIC_DEVICE_ADDRESS
RND = A.RANDOM_DEVICE_ADDRESS


def addr(v, kind):
    s = "%012x" % v
    return A(":".join(s[i:i + 2] for i in range(0, 12, 2)), kind)


def hx(x):
    return bytes(x).hex()


MASK = 0x3DBFF807FFFBFFFF
ADV = bytes.fromhex("020106 09 09 4669726e4c45".replace(" ", ""))
KEY = bytes(range(16))

