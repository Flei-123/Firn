def adv_event(reports):
    return hci.HCI_LE_Advertising_Report_Event(reports=[
        REPORT(event_type=t, address_type=at, address=addr(a, RND if at else PUB), data=d, rssi=r)
        for (t, at, a, d, r) in reports])


