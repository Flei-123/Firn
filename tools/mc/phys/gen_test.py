import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ref

K_F, K_B, K_L, K_R, K_J, K_SN, K_SP = 1, 2, 4, 8, 16, 32, 64
W = K_F
S = K_F | K_SP
N = 0
J = K_J
SCENARIOS = [
    ("jump_stand", 0.6, 0.0, [J] + [N] * 13),
    ("walk_start_stop", 0.6, 0.0, [W] * 10 + [N] * 14),
    ("sprint_run_stop", 0.6, 0.0, [S] * 10 + [N] * 16),
    ("sprint_jump", 0.6, 0.0, [S] * 12 + [S | J] + [S] * 16),
    ("sprint_hop_hold", 0.6, 0.0, [S | J] * 30),
    ("sneak_walk", 0.6, 0.0, [W | K_SN] * 10 + [N] * 8),
    ("air_control", 0.6, 0.0, [J] + [W] * 14),
    ("strafe_diag", 0.6, 45.0, [W | K_L] * 10 + [N] * 6),
    ("ice_walk", 0.98, 0.0, [W] * 20 + [N] * 20),
    ("sneak_diag_back", 0.6, 90.0, [K_B | K_R | K_SN] * 8 + [N] * 6),
]

def tup(k):
    fwd = 1 if k & K_F else (-1 if k & K_B else 0)
    if k & K_F and k & K_B:
        fwd = 0
    left = 1 if k & K_L else (-1 if k & K_R else 0)
    if k & K_L and k & K_R:
        left = 0
    return (fwd, left, 1 if k & K_J else 0, 1 if k & K_SN else 0, 1 if k & K_SP else 0)

out = []
out.append("// expect_exit: 0\n// tests/5750_mc_phys_vanilla.fi -- per-tick positions of the player physics against the vanilla 1.20.1 formulas (tools/mc/phys/ref.py, generated by gen_test.py)\n")
out.append("""import std.rt
import mc.mc_world
import mc.mc_render_world
import mc.mc_input
import mc.mc_slide
import mc.mc_phys

static mut g_fail: i32 = 0

fn fail(code: i32) {
    var o: rt.Buf = rt.buf_new()
    rt.buf_push_bytes(&o, "FAIL ".p as u64, 5)
    rt.buf_push_hex_u64(&o, code as u64, 4)
    rt.buf_push(&o, 10)
    rt.write_everything(1, rt.buf_ptr(&o), rt.buf_len(&o))
    rt.buf_free(&o)
    g_fail = g_fail + 1
}

fn near(a: f64, b: f64) -> bool {
    var d: f64 = a - b
    if d < 0.0 { d = 0.0 - d }
    return d < 0.0000001
}

const STONE: u16 = 1 as u16
const ICE: u16 = 5 as u16

fn put(ids: u64, x: i32, ly: i32, z: i32, id: u16) {
    rt.st16(ids, ((ly * 16 + z) * 16 + x) as usize, id)
}

fn make_world(w: *mut mc_world.World, top: u16) {
    let ids: u64 = rt.heap_alloc(2 * 4096 * 2)
    var i: usize = 0
    while i < 8192 {
        rt.st16(ids, i, 0 as u16)
        i = i + 1
    }
    var ly: i32 = 0
    while ly < 3 {
        var z: i32 = 0
        while z < 16 {
            var x: i32 = 0
            while x < 16 {
                var id: u16 = STONE
                if ly == 2 { id = top }
                put(ids, x, ly, z, id)
                x = x + 1
            }
            z = z + 1
        }
        ly = ly + 1
    }
    mc_world.world_put(w, mc_render_world.wr_make_chunk(0, 0, 2, ids))
}

fn run(code: i32, top: u16, yaw: f64, keys: *mut [u32; 64], expect: *mut [f64; 192], n: i32) {
    var tb: mc_input.InputTables = mc_input.InputTables { pick: rt.heap_alloc(8), solid: rt.heap_alloc(16), n: 8 }
    var i: usize = 0
    while i < 8 {
        rt.st8(tb.pick, i, 1 as u8)
        rt.st16(tb.solid, i, 0 as u16)
        i = i + 1
    }
    rt.st16(tb.solid, STONE as usize, 1 as u16)
    rt.st16(tb.solid, ICE as usize, 1 as u16)
    var w: mc_world.World = mc_world.world_new()
    make_world(&w, top)
    var p: mc_input.Player = mc_input.player_new(8.5, 0.0 - 60.9, 2.5)
    rt.st8(p.mv, ICE as usize, mc_slide.MV_ICE as u8)
    p.yaw = yaw
    var ev: mc_input.InputEvents = mc_input.input_events_new()
    var t: i32 = 0
    while t < 4 {
        mc_input.player_tick(&p, &ev, &w, &tb, 0 - 64)
        t = t + 1
    }
    if !p.on_ground { fail(code * 1000) }
    let x0: f64 = p.x
    let y0: f64 = p.y
    let z0: f64 = p.z
    t = 0
    while t < n {
        ev.keys = (*keys)[t as usize]
        mc_input.player_tick(&p, &ev, &w, &tb, 0 - 64)
        if !near(p.x - x0, (*expect)[(t * 3) as usize]) { fail(code * 1000 + t * 4 + 1) }
        if !near(p.y - y0, (*expect)[(t * 3 + 1) as usize]) { fail(code * 1000 + t * 4 + 2) }
        if !near(p.z - z0, (*expect)[(t * 3 + 2) as usize]) { fail(code * 1000 + t * 4 + 3) }
        t = t + 1
    }
    mc_input.player_free(&p)
}

""")
calls = []
for idx, (name, fr, yaw, keys) in enumerate(SCENARIOS, 1):
    rows = ref.sim([tup(k) for k in keys], floor_friction=fr, yaw=yaw)
    n = len(keys)
    assert n <= 64
    kk = ", ".join(str(k) + " as u32" for k in keys + [0] * (64 - n))
    ee = ", ".join("%.12f" % v for r in rows for v in r)
    ee += ", " + ", ".join(["0.0"] * (192 - 3 * n)) if n < 64 else ""
    out.append("fn sc_%s() {\n    var keys: [u32; 64] = [%s]\n    var expect: [f64; 192] = [%s]\n    run(%d, %s, %.1f, &keys, &expect, %d)\n}\n" % (name, kk, ee, idx, "ICE" if fr > 0.9 else "STONE", yaw, n))
    calls.append("    sc_%s()\n" % name)
out.append("fn main() -> i32 {\n" + "".join(calls) + "    var o: rt.Buf = rt.buf_new()\n    rt.buf_push_bytes(&o, \"fails \".p as u64, 6)\n    rt.buf_push_hex_u64(&o, g_fail as u64, 2)\n    rt.buf_push(&o, 10)\n    rt.write_everything(1, rt.buf_ptr(&o), rt.buf_len(&o))\n    rt.buf_free(&o)\n    return g_fail\n}\n")
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tests/5750_mc_phys_vanilla.fi"), "w").write("\n".join(out))
