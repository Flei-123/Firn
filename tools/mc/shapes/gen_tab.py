#!/usr/bin/env python3
"""gen_tab.py <minecraft-data/data/pc/1.20 dir> <out .fi> -- generates lib/mc/mc_shape_data.fi: the collision shapes of the blocks with a
partial shape that mc_shapes does not model by rule (candles, bell, chain, lantern, dripleaf, ladder, cactus, pots, heads, piston ...).
Data = per block one shape index per block state (offset inside the block's state range), a pool of distinct shapes, all in 1/32 units.
Coordinate = 2 letters (base 26) of 1/32 units + 32 (so -1..3 blocks are possible: piston heads, pitcher crop). Deterministic; run.sh regenerates and diffs against the committed file."""
import json, sys
d, out = sys.argv[1], sys.argv[2]
cs = json.load(open(d + "/blockCollisionShapes.json"))
bl = json.load(open(d + "/blocks.json"))
shapes = cs["shapes"]
RULE = ("_slab", "_stairs", "_carpet", "_fence", "_fence_gate", "_wall", "_door", "_trapdoor", "_bed", "glass_pane", "anvil", "cauldron")
RULE_EXACT = {"snow", "chest", "trapped_chest", "ender_chest", "iron_bars", "hopper", "farmland", "dirt_path", "soul_sand", "mud", "honey_block"}
CUBE = [[0, 0, 0, 1, 1, 1]]

def b32(c):
    v = c * 32
    assert abs(v - round(v)) < 1e-9, c
    return round(v)

pool = []   # list of tuples of boxes (each box 6 ints in 1/32)
pidx = {}
rows = []   # (name, [value per state]) value 0 passable, 1 full, 2+ pool
for b in sorted(bl, key=lambda x: x["minStateId"]):
    n = b["name"]
    if n.endswith(RULE) or n in RULE_EXACT:
        continue
    ids = cs["blocks"][n]
    ids = ids if isinstance(ids, list) else [ids]
    if not any(shapes[str(i)] not in ([], CUBE) for i in ids):
        continue
    vals = []
    nst = b["maxStateId"] - b["minStateId"] + 1
    for st in range(nst):
        sid = ids[st] if len(ids) > 1 else ids[0]
        bx = shapes[str(sid)]
        if bx == []:
            vals.append(0)
        elif bx == CUBE:
            vals.append(1)
        else:
            t = tuple(tuple(b32(c) for c in x) for x in bx)
            if t not in pidx:
                pidx[t] = len(pool)
                pool.append(t)
            vals.append(2 + pidx[t])
    rows.append((n, vals))

def ch(v):
    assert -32 <= v <= 96, v
    return b26(v + 32, 2)
def b26(v, w):
    s = ""
    for _ in range(w):
        s = chr(97 + v % 26) + s
        v //= 26
    assert v == 0
    return s

names = "".join(n + ";" for n, _ in rows)
rowoff = ""
states = ""
for n, vals in rows:
    rowoff += b26(len(states) // 2, 4)
    states += "".join(b26(v, 2) for v in vals)
rowoff += b26(len(states) // 2, 4)
boxes = ""
poolidx = ""
nbox = 0
for t in pool:
    poolidx += b26(nbox, 3) + chr(97 + len(t))
    for x in t:
        boxes += "".join(ch(c) for c in x)
    nbox += len(t)
assert all(len(t) < 26 for t in pool) and len(pool) + 2 < 676
src = f'''// SPDX-License-Identifier: MPL-2.0
// lib/mc/mc_shape_data.fi -- GENERATED by tools/mc/shapes/gen_tab.py from minecraft-data 1.20 blockCollisionShapes. Do not edit.
// {len(rows)} blocks, {sum(len(v) for _, v in rows)} states, {len(pool)} distinct shapes. See the generator for the encoding.
import std.rt

export {{ names, rowoff, states, poolidx, boxes, NBLOCKS, NPOOL }}

const NBLOCKS: i32 = {len(rows)}
const NPOOL: i32 = {len(pool)}

// block names, each followed by ';'
fn names() -> str {{ return "{names}" }}
// NBLOCKS + 1 entries of 4 letters (base 26): offset of the block's first state in `states` (in states)
fn rowoff() -> str {{ return "{rowoff}" }}
// per state 2 letters (base 26): 0 no collision, 1 full cube, 2 + n pool shape n
fn states() -> str {{ return "{states}" }}
// per pool shape 4 chars: first box (3 letters base 26) + box count ('a' + n)
fn poolidx() -> str {{ return "{poolidx}" }}
// 12 chars per box (x0 y0 z0 x1 y1 z1), 2 letters (base 26) per coordinate = 1/32 units + 32
fn boxes() -> str {{ return "{boxes}" }}
'''
open(out, "w").write(src)
print("blocks", len(rows), "states", sum(len(v) for _, v in rows), "pool", len(pool), "boxes", nbox, "bytes", len(src))
