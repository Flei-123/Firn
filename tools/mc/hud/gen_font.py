#!/usr/bin/env python3
"""tools/mc/hud/gen_font.py -- font5x7.txt -> lib/mc/mc_hud_font.fi (generated; run.sh checks it is up to date).
Layout of HUD_FONT: 95 glyphs (ASCII 32..126) x 7 bytes, one byte per row, bit 4 = leftmost cell."""
import sys

def load(path):
    glyphs = {}
    for line in open(path):
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        parts = line.split()
        code = int(parts[0])
        rows = parts[1:]
        assert len(rows) == 7 and all(len(r) == 5 and set(r) <= set('#.') for r in rows), line
        assert 32 <= code <= 126 and code not in glyphs, line
        glyphs[code] = rows
    assert sorted(glyphs) == list(range(32, 127)), 'font must cover ASCII 32..126'
    return glyphs

def render(glyphs):
    data = bytearray()
    for code in range(32, 127):
        for r in glyphs[code]:
            data.append(int(r.replace('#', '1').replace('.', '0'), 2))
    esc = ''.join('\\x%02x' % b for b in data)
    return ('// GENERATED by tools/mc/hud/gen_font.py from tools/mc/hud/font5x7.txt - do not edit\n'
            '//\n'
            '// lib/mc/mc_hud_font.fi -- own 5x7 bitmap font, ASCII 32..126, 7 bytes per glyph (bit 4 = left cell).\n'
            '\n'
            'export {\n    HUD_FONT,\n}\n'
            '\n'
            'const HUD_FONT: str = "%s"\n' % esc)

if __name__ == '__main__':
    src, dst = sys.argv[1], sys.argv[2]
    open(dst, 'w').write(render(load(src)))
