#!/usr/bin/env python3
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "mcgen"))
from gen_protocol import lit_string


def split_names(args):
    names = []
    levels = {}
    for a in args:
        name, _, level = a.partition("=")
        names.append(name)
        levels[name] = int(level) if level else 0
    return sorted(names), levels


def entity_types(report_dir):
    registries = json.load(open(os.path.join(report_dir, "registries.json")))
    return sorted(registries["minecraft:entity_type"]["entries"])


def subset(report_dir, names):
    commands = json.load(open(os.path.join(report_dir, "commands.json")))
    registries = json.load(open(os.path.join(report_dir, "registries.json")))
    parsers = registries["minecraft:command_argument_type"]["entries"]
    root = {"type": "root", "children": {}}
    for n in names:
        root["children"][n] = commands["children"][n]
    table = sorted(("%s=%d" % (k, v["protocol_id"])) for k, v in parsers.items())
    return root, table


def emit(protocol, root, table, types, levels, out_path):
    body = json.dumps(root, separators=(",", ":"))
    lines = [
        "// SPDX-License-Identifier: MPL-2.0",
        "// GENERATED by tools/mc/cmd/gen_cmd_data.py - do not edit",
        "// lib/mc/cmd/data/cmd_data_v%d.fi -- command tree subset and parser ids of protocol %d." % (protocol, protocol),
        "",
        "export { cmd_json, cmd_parsers, cmd_entity_types, cmd_levels }",
        "",
        "fn cmd_json() -> str {",
        '    return "%s"' % lit_string(body.encode("ascii")),
        "}",
        "",
        "fn cmd_parsers() -> str {",
        '    return "%s"' % lit_string(("\n".join(table) + "\n").encode("ascii")),
        "}",
        "",
        "fn cmd_entity_types() -> str {",
        '    return "%s"' % lit_string(("\n".join(types) + "\n").encode("ascii")),
        "}",
        "",
        "fn cmd_levels() -> str {",
        '    return "%s"' % lit_string(("\n".join("%s=%d" % (k, levels[k]) for k in sorted(levels)) + "\n").encode("ascii")),
        "}",
    ]
    with open(out_path, "w") as fh:
        fh.write("\n".join(lines) + "\n")


def emit_registry(data_dir):
    versions = sorted(int(f[len("cmd_data_v"):-3]) for f in os.listdir(data_dir) if f.startswith("cmd_data_v"))
    lines = [
        "// SPDX-License-Identifier: MPL-2.0",
        "// GENERATED by tools/mc/cmd/gen_cmd_data.py - do not edit",
        "// lib/mc/cmd/data/cmd_data.fi -- command tree data per protocol version.",
        "",
    ]
    for v in versions:
        lines.append("import mc.cmd.data.cmd_data_v%d" % v)
    lines += ["", "export { data_for, entity_types_for, levels_for }", "", "fn data_for(protocol: i32, json: *mut str, parsers: *mut str) -> bool {"]
    for v in versions:
        lines += [
            "    if protocol == %d {" % v,
            "        *json = cmd_data_v%d.cmd_json()" % v,
            "        *parsers = cmd_data_v%d.cmd_parsers()" % v,
            "        return true",
            "    }",
        ]
    lines += ["    return false", "}"]
    for fn, getter in (("entity_types_for", "cmd_entity_types"), ("levels_for", "cmd_levels")):
        lines += ["", "fn %s(protocol: i32) -> str {" % fn]
        for v in versions:
            lines += ["    if protocol == %d {" % v, "        return cmd_data_v%d.%s()" % (v, getter), "    }"]
        lines += ['    return ""', "}"]
    with open(os.path.join(data_dir, "cmd_data.fi"), "w") as fh:
        fh.write("\n".join(lines) + "\n")


def main():
    report_dir, protocol, lib_dir = sys.argv[1], int(sys.argv[2]), sys.argv[3]
    names, levels = split_names(sys.argv[4:])
    root, table = subset(report_dir, names)
    data_dir = os.path.join(lib_dir, "mc", "cmd", "data")
    os.makedirs(data_dir, exist_ok=True)
    emit(protocol, root, table, entity_types(report_dir), levels, os.path.join(data_dir, "cmd_data_v%d.fi" % protocol))
    emit_registry(data_dir)


if __name__ == "__main__":
    main()
