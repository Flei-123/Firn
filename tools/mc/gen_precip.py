#!/usr/bin/env python3
"""Generates lib/mc/mc_precip_tab.fi: biome name -> precipitation kind (0 none, 1 rain, 2 snow).

usage: gen_precip.py <minecraft-data/data/pc/1.20/biomes.json> <out.fi>
Snow when the base temperature is below 0.15 (vanilla coldEnoughToSnow without the height adjustment).
"""
import json, sys

SNOW_BELOW = 0.15


def kind(b):
    if not b['has_precipitation']:
        return 0
    return 2 if b['temperature'] < SNOW_BELOW else 1


def main():
    biomes = json.load(open(sys.argv[1]))
    data = ';'.join('%s:%d' % (b['name'], kind(b)) for b in sorted(biomes, key=lambda b: b['name']))
    src = '// SPDX-License-Identifier: MPL-2.0\n'
    src += '// lib/mc/mc_precip_tab.fi -- GENERATED by tools/mc/gen_precip.py, do not edit.\n'
    src += 'import std.core\n\nexport { PRECIP_DATA, PRECIP_LEN }\n\n'
    src += 'const PRECIP_LEN: usize = %d\n' % len(data)
    src += 'const PRECIP_DATA: str = "%s"\n' % data
    open(sys.argv[2], 'w').write(src)
    print('biomes', len(biomes), 'chars', len(data))


main()
