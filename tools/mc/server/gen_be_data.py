#!/usr/bin/env python3
import json
import sys

FULL = {"sign", "hanging_sign", "skull", "banner", "beacon", "piston", "campfire", "conduit", "end_gateway", "structure_block",
        "jigsaw", "lectern", "chiseled_bookshelf", "decorated_pot"}
SPAWNER = {"mob_spawner"}
BRUSHABLE = {"brushable_block"}


def mode_of(name):
    if name in FULL:
        return 1
    if name in SPAWNER:
        return 2
    if name in BRUSHABLE:
        return 3
    return 0


def main():
    reg = json.load(open(sys.argv[1]))["minecraft:block_entity_type"]["entries"]
    items = sorted(reg.items(), key=lambda kv: kv[1]["protocol_id"])
    for i, (_, v) in enumerate(items):
        assert v["protocol_id"] == i
    rows = ["%s:%d" % (k.split(":", 1)[1], mode_of(k.split(":", 1)[1])) for k, _ in items]
    out = ["// SPDX-License-Identifier: MPL-2.0", "// GENERATED by tools/mc/server/gen_be_data.py - do not edit", "",
           "export { BE_TABLE }", "", 'const BE_TABLE: str = "%s\\n"' % "\\n".join(rows), ""]
    open(sys.argv[2], "w").write("\n".join(out))


main()
