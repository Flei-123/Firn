#!/bin/sh
set -e
root=$(cd "$(dirname "$0")/../.." && pwd)
names=$(ls "$root/lib/std" | grep '\.fi$' | sed 's/\..*$//' | LC_ALL=C sort -u)
count=$(echo "$names" | wc -l)
rs="$root/compiler/src/std_modules.rs"
fi_out="$root/lib/firnc1/std_modules.fi"
{
    echo "// SPDX-License-Identifier: MPL-2.0"
    echo "// Generated by tools/stdimport/gen.sh from lib/std. Do not edit."
    echo "pub(crate) const STD_MODULES: [&str; $count] = ["
    for n in $names; do echo "    \"$n\","; done
    echo "];"
} > "$rs"
packed=$(echo "$names" | paste -sd'|')
len=$(printf '%s' "$packed" | wc -c)
{
    echo "// SPDX-License-Identifier: MPL-2.0"
    echo "// Generated by tools/stdimport/gen.sh from lib/std. Do not edit."
    echo "export { STD_MODULE_COUNT, STD_MODULE_TEXT_LEN, STD_MODULE_TEXT }"
    echo
    echo "const STD_MODULE_COUNT: usize = $count"
    echo "const STD_MODULE_TEXT_LEN: usize = $len"
    echo "static STD_MODULE_TEXT: [u8; $len] = \"$packed\""
} > "$fi_out"
