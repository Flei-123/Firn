#!/usr/bin/env python3
"""gen_firn.py SCRIPT ASSETS OUT.f32 > scenario.fi
Turns a scenario script (grammar: see aulos_offline.cpp / docs/AUDIO.md) into a Firn
program that drives audio.engine the same way and writes the same raw f32 stream."""
import sys

script, assets, out = sys.argv[1:4]
o = []
def w(s): o.append(s)

def lit(x):
    f = float(x)
    s = repr(f)
    return s if ('.' in s or 'e' in s) else s + '.0'

def neg(x):  # Firn has no unary minus on literals in every context: 0.0 - x
    return lit(x)

def cstr(s): return '"' + s + '"'

rate, voices = 48000, 64
buses, events, rt_lines = [], [], []
for ln in open(script):
    ln = ln.split('#')[0].split()
    if not ln: continue
    c = ln[0]
    if c == 'rate': rate = int(ln[1])
    elif c == 'voices': voices = int(ln[1])
    elif c == 'bus': buses.append((ln[1], ln[2] if len(ln) > 2 else ''))
    elif c == 'event':
        kv = dict(a.split('=', 1) for a in ln[4:])
        events.append(dict(name=ln[1], bus=ln[2], files=ln[3].split(','), kv=kv, params=[]))
    elif c == 'param':
        ev = [e for e in events if e['name'] == ln[1]][0]
        ev['params'].append((ln[2], ln[3], ln[4], [tuple(p.split(':')) for p in ln[5].split(',')]))
    else: rt_lines.append(ln)

w('// GENERATED by tools/audio/aulos/gen_firn.py -- do not edit.')
w('import std.rt\nimport std.io\nimport std.math\nimport audio.engine\n')
w('fn load(e: *mut engine.Engine, dir: str, name: str) -> i32 {')
w('    var path: rt.Buf = rt.buf_new()')
w('    rt.buf_push_bytes(&path, dir.p as u64, dir.length())')
w('    rt.buf_push(&path, 47 as u8)')
w('    rt.buf_push_bytes(&path, name.p as u64, name.length())')
w('    rt.buf_push(&path, 0 as u8)')
w('    var data: rt.Buf = rt.buf_new()')
w('    if !rt.read_file(rt.buf_ptr(&path), &data) { return -1 }')
w('    if name.length() > 4 && rt.ld8(name.p as u64, name.length() - 1) == 51 as u8 {')
w('        return engine.engine_load_mp3(e, rt.buf_ptr(&data), rt.buf_len(&data))')
w('    }')
w('    let id: i32 = engine.engine_load_wav(e, rt.buf_ptr(&data), rt.buf_len(&data))')
w('    return id')
w('}\n')
w('fn main(start: u64) -> i32 {')
w(f'    var e: engine.Engine = engine.engine_new({rate} as u32, {voices} as u32)')
for name, parent in buses:
    if name == 'master': continue
    w(f'    engine.engine_ensure_bus(&e, {cstr(name)}, {cstr(parent)})')
files = {}
for ev in events:
    for f in ev['files']:
        if f not in files:
            files[f] = len(files)
            w(f'    let s{files[f]}: i32 = load(&e, {cstr(assets)}, {cstr(f)})')
            w(f'    if s{files[f]} < 0 {{ return 3 }}')
for i, ev in enumerate(events):
    kv = ev['kv']
    w(f'    let ev{i}: i32 = engine.engine_add_event(&e, {cstr(ev["name"])}, engine.engine_bus_id(&e, {cstr(ev["bus"])}))')
    for f in ev['files']:
        w(f'    engine.engine_event_add_sample(&e, ev{i}, s{files[f]})')
    fields = dict(volume='volume', pitch='pitch', vol_rand='volume_random', pitch_rand='pitch_random',
                  min='min_distance', max='max_distance', factor='rolloff_factor', doppler='doppler', lowpass='lowpass_hz')
    w(f'    let d{i}: *mut engine.EventDef = engine.engine_event(&e, ev{i})')
    for k, f in fields.items():
        if k in kv: w(f'    (*d{i}).{f} = {lit(kv[k])}')
    if 'loop' in kv: w(f'    (*d{i}).looping = {"true" if kv["loop"] == "1" else "false"}')
    if 'spatial' in kv: w(f'    (*d{i}).spatial = {"true" if kv["spatial"] == "1" else "false"}')
    if 'rolloff' in kv: w(f'    (*d{i}).rolloff = {int(kv["rolloff"])}')
    if 'priority' in kv: w(f'    (*d{i}).priority = {int(kv["priority"])}')
    if 'maxinst' in kv: w(f'    (*d{i}).max_instances = {int(kv["maxinst"])}')
    for j, (pn, tgt, dflt, pts) in enumerate(ev['params']):
        w(f'    let xs{i}_{j}: u64 = rt.heap_alloc(128)')
        w(f'    let ys{i}_{j}: u64 = rt.heap_alloc(128)')
        for m, (x, y) in enumerate(pts):
            w(f'    rt.st32(xs{i}_{j}, {m}, math.math_bits32({lit(x)}))')
            w(f'    rt.st32(ys{i}_{j}, {m}, math.math_bits32({lit(y)}))')
        t = dict(volume='engine.PARAM_VOLUME', pitch='engine.PARAM_PITCH', lowpass='engine.PARAM_LOWPASS')[tgt]
        w(f'    engine.engine_event_add_param(&e, ev{i}, {cstr(pn)}, {t}, {lit(dflt)}, {len(pts)}, xs{i}_{j}, ys{i}_{j})')
w('    var total: usize = 0')
frames_total = sum(int(l[1]) for l in rt_lines if l[0] == 'render')
w(f'    let buf: u64 = rt.heap_alloc({frames_total} * 8 + 8)')
nh = 0
for t in rt_lines:
    c = t[0]
    if c == 'listener':
        a = ', '.join(lit(x) for x in t[1:13])
        w(f'    engine.engine_set_listener(&e, {a})')
    elif c == 'play':
        b = f'engine.engine_bus_id(&e, {cstr(t[2])})' if len(t) > 2 else '-1'
        w(f'    let h{nh}: u32 = engine.engine_play(&e, engine.engine_find_event(&e, {cstr(t[1])}), {b})'); nh += 1
    elif c == 'play3d':
        b = f'engine.engine_bus_id(&e, {cstr(t[5])})' if len(t) > 5 else '-1'
        w(f'    let h{nh}: u32 = engine.engine_play_3d(&e, engine.engine_find_event(&e, {cstr(t[1])}), {b}, {lit(t[2])}, {lit(t[3])}, {lit(t[4])})'); nh += 1
    elif c == 'stop': w(f'    engine.engine_stop(&e, h{t[1]}, {lit(t[2])})')
    elif c == 'stopall': w(f'    engine.engine_stop_all(&e, {lit(t[1])})')
    elif c == 'setvol': w(f'    engine.engine_set_volume(&e, h{t[1]}, {lit(t[2])})')
    elif c == 'setpitch': w(f'    engine.engine_set_pitch(&e, h{t[1]}, {lit(t[2])})')
    elif c == 'setpos': w(f'    engine.engine_set_position(&e, h{t[1]}, ' + ', '.join(lit(x) for x in t[2:8]) + ')')
    elif c == 'setparam': w(f'    engine.engine_set_param(&e, h{t[1]}, {cstr(t[2])}, {lit(t[3])})')
    elif c == 'mute': w(f'    engine.engine_set_bus_mute(&e, {cstr(t[1])}, {"true" if t[2] == "1" else "false"})')
    elif c == 'busvol': w(f'    engine.engine_set_bus_volume(&e, {cstr(t[1])}, {lit(t[2])})')
    elif c == 'update': w('    engine.engine_update(&e)')
    elif c == 'render':
        w(f'    engine.engine_render(&e, buf + (total * 8) as u64, {int(t[1])})')
        w(f'    total = total + {int(t[1])}')
w("    var op: rt.Buf = rt.buf_new()")
w(f'    rt.buf_push_bytes(&op, {cstr(out)}.p as u64, {cstr(out)}.length())')
w("    rt.buf_push(&op, 0 as u8)")
w("    rt.write_file(rt.buf_ptr(&op), buf, total * 8)")
w("    let st: engine.Stats = engine.engine_stats(&e)")
w("    let sa: u64 = st.active_voices as u64")
w("    let ss: u64 = st.started")
w("    let sl: u64 = st.stolen")
w("    let sd: u64 = st.dropped")
w('    io.fmt_print(f"STATS active={sa} started={ss} stolen={sl} dropped={sd}\\n")')
w('    return 0')
w('}')
print('\n'.join(o))
