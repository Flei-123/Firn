#!/usr/bin/env python3
"""tools/vorbis/gen_tab.py -- generates lib/ton/vorbis_tab.fi.

The only table the Vorbis decoder cannot compute is the floor1 "inverse dB"
table (256 floats, from 1.0649863e-07 up to 1.0). The Vorbis I specification
prints it; libvorbis (BSD-3-Clause) ships it as FLOOR1_fromdB_LOOKUP in
lib/floor1.c. The values do not follow one closed formula to the last bit
(10^(x/20) differs by up to 6.8e-7), so they are COPIED, not recomputed.

Usage: python3 tools/vorbis/gen_tab.py /usr/lib/x86_64-linux-gnu/libvorbis.so.0 > lib/ton/vorbis_tab.fi
The table is found in the shared object by its first float (1.0649863e-07).
"""
import struct, sys

def main():
    path = sys.argv[1]
    d = open(path, 'rb').read()
    key = struct.pack('<f', 1.0649863e-07)
    i = d.find(key)
    if i < 0:
        sys.exit("table not found in " + path)
    t = struct.unpack('<256f', d[i:i + 1024])
    assert abs(t[255] - 1.0) < 1e-9 and all(t[k] < t[k + 1] for k in range(255))
    out = []
    out.append("// SPDX-License-Identifier: MPL-2.0")
    out.append("// lib/ton/vorbis_tab.fi -- the floor1 inverse dB table. GENERATED, NOT TYPED.")
    out.append("//")
    out.append("// Generated by tools/vorbis/gen_tab.py from the table of the Vorbis I specification")
    out.append("// (as shipped in libvorbis, BSD-3-Clause, lib/floor1.c FLOOR1_fromdB_LOOKUP).")
    out.append("// 256 floats: index 0 = 1.0649863e-07 (about -139.5 dB), index 255 = 1.0.")
    out.append("")
    out.append("export { vorbis_db_table }")
    out.append("")
    out.append("fn vorbis_db_table() -> [f32; 256] {")
    out.append("    return [")
    row = []
    for k, x in enumerate(t):
        row.append("%.9gf" % x)
        if len(row) == 4:
            out.append("        " + ", ".join(row) + ",")
            row = []
    out.append("    ]")
    out.append("}")
    print("\n".join(out))

main()
