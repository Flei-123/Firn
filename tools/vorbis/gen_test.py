# Generates tests/2780_vorbis.fi from the reference decoder (libsndfile via soundfile).
import glob, os, numpy as np, soundfile as sf
files = sorted(glob.glob('tests/data/vorbis/*.ogg'))
rows = []
for f in files:
    f32, sr = sf.read(f, dtype='float32', always_2d=True)
    i16, _ = sf.read(f, dtype='int16', always_2d=True)
    mid = max(0, len(f32) // 2 - 12)
    snip = i16[mid:mid + 24].reshape(-1)[:24]
    ssum = float(np.abs(f32.astype('f8')).sum())
    rows.append((f, sr, f32.shape[1], len(f32), mid, ssum, [int(x) for x in snip]))
out = ['// expect_exit: 0',
'// tests/2780_vorbis.fi -- ton.vorbis_file / audio.load_ogg against libsndfile (generated by tools/vorbis/gen_test.py).',
'// Per file: rate, channels, frame count, sum of |x| (relative 2e-5) and 24 frames of 16 bit PCM from the middle (+-1 LSB).',
'// Then damaged input: truncated / garbage files must give a clean error or fewer frames, never a crash.',
'import std.rt',
'import audio.engine',
'import audio.load_ogg',
'import ton.vorbis_file',
'',
'fn check(c: bool, code: i32) {',
'    if !c {',
'        rt.finish(code as i64)',
'    }',
'}',
'',
'fn load(path: str, buf: *mut rt.Buf) -> bool {',
'    var p: rt.Buf = rt.buf_new()',
'    rt.buf_push_bytes(&p, path.p as u64, path.length())',
'    rt.buf_push(&p, 0 as u8)',
'    let ok: bool = rt.read_file(rt.buf_ptr(&p), buf)',
'    rt.buf_free(&p)',
'    return ok',
'}',
'',
'fn abs_i(x: i32) -> i32 {',
'    if x < 0 { return 0 - x }',
'    return x',
'}',
'',
'fn one(path: str, rate: i32, ch: i32, frames: i64, mid: i64, ssum: f64, snip: [i16; 24], code: i32) {',
'    var src: rt.Buf = rt.buf_new()',
'    check(load(path, &src), code + 1)',
'    var pcm: rt.Buf = rt.buf_new()',
'    var info: vorbis_file.VfInfo = vorbis_file.vf_info()',
'    check(vorbis_file.vf_decode_f32(rt.buf_ptr(&src), rt.buf_len(&src), &pcm, &info) == 0, code + 2)',
'    check(info.rate == rate && info.channels == ch && info.frames == frames && info.bad_packets == 0, code + 3)',
'    check(rt.buf_len(&pcm) == (frames as usize) * (ch as usize) * 4, code + 4)',
'    var s: f64 = 0.0',
'    var i: usize = 0',
'    let n: usize = (frames as usize) * (ch as usize)',
'    while i < n {',
'        var x: f64 = (*((rt.buf_ptr(&pcm) + (i * 4) as u64) as *mut f32)) as f64',
'        if x < 0.0 { x = 0.0 - x }',
'        s = s + x',
'        i = i + 1',
'    }',
'    var d: f64 = s - ssum',
'    if d < 0.0 { d = 0.0 - d }',
'    check(d <= ssum * 0.00002 + 0.001, code + 5)',
'    var pcm16: rt.Buf = rt.buf_new()',
'    var info16: vorbis_file.VfInfo = vorbis_file.vf_info()',
'    check(vorbis_file.vf_decode_i16(rt.buf_ptr(&src), rt.buf_len(&src), &pcm16, &info16) == 0, code + 6)',
'    check(info16.frames == frames, code + 7)',
'    var k: usize = 0',
'    while k < 24 {',
'        let v: i32 = (*((rt.buf_ptr(&pcm16) + (((mid as usize) * (ch as usize) + k) * 2) as u64) as *mut i16)) as i32',
'        check(abs_i(v - (snip[k] as i32)) <= 1, code + 8)',
'        k = k + 1',
'    }',
'    rt.buf_free(&src)',
'    rt.buf_free(&pcm)',
'    rt.buf_free(&pcm16)',
'}',
'',
'fn damaged(path: str, code: i32) {',
'    var src: rt.Buf = rt.buf_new()',
'    check(load(path, &src), code + 1)',
'    let len: usize = rt.buf_len(&src)',
'    var cut: usize = 0',
'    while cut < len {',
'        var pcm: rt.Buf = rt.buf_new()',
'        var info: vorbis_file.VfInfo = vorbis_file.vf_info()',
'        let st: i32 = vorbis_file.vf_decode_f32(rt.buf_ptr(&src), cut, &pcm, &info)',
'        check(st == 0 || st < 0, code + 2)',
'        rt.buf_free(&pcm)',
'        cut = cut + len / 37 + 1',
'    }',
'    // flip one byte every 997 in the file (CRC rejects the pages: clean result expected)',
'    var i: usize = 0',
'    while i < len {',
'        let q: u64 = rt.buf_ptr(&src) + (i as u64)',
'        *(q as *mut u8) = (*(q as *mut u8)) ^ (85 as u8)',
'        i = i + 997',
'    }',
'    var pcm2: rt.Buf = rt.buf_new()',
'    var info2: vorbis_file.VfInfo = vorbis_file.vf_info()',
'    let st2: i32 = vorbis_file.vf_decode_f32(rt.buf_ptr(&src), len, &pcm2, &info2)',
'    check(st2 == 0 || st2 < 0, code + 3)',
'    rt.buf_free(&pcm2)',
'    rt.buf_free(&src)',
'}',
'',
'fn main() -> i32 {']
code = 10
for (f, sr, ch, n, mid, ssum, snip) in rows:
    out.append('    one("%s", %d, %d, %d, %d, %r, [%s], %d)' % (f, sr, ch, n, mid, ssum, ', '.join(str(x) + ' as i16' if False else str(x) for x in snip), code))
    code += 20
out += ['    // audio.load_ogg: engine at 48 kHz, file at 22.05 kHz -> resampled, 2 channels max',
'    var e: engine.Engine = engine.engine_new(48000 as u32, 8 as u32)',
'    var src: rt.Buf = rt.buf_new()',
'    check(load("tests/data/vorbis/sine_m22k_q3.ogg", &src), 900)',
'    let id: i32 = load_ogg.ogg_load(&e, rt.buf_ptr(&src), rt.buf_len(&src))',
'    check(id >= 0, 901)',
'    check(engine.engine_sample_frames(&e, id) == 22050 * 48000 / 22050, 902)',
'    var six: rt.Buf = rt.buf_new()',
'    check(load("tests/data/vorbis/pink_6ch_q4.ogg", &six), 903)',
'    check(load_ogg.ogg_load(&e, rt.buf_ptr(&six), rt.buf_len(&six)) >= 0, 904)',
'    check(load_ogg.ogg_load(&e, rt.buf_ptr(&src), 100) < 0, 905)',
'    engine.engine_free(&e)',
'    damaged("tests/data/vorbis/tone_s48k_q0.ogg", 1000)',
'    damaged("tests/data/vorbis/pink_6ch_q4.ogg", 1010)',
'    return 0',
'}']
open('tests/2780_vorbis.fi', 'w').write('\n'.join(out) + '\n')
