"""gen_recipes.py <data_dir> <version> <pver> <out.fi> -- crafting recipes of one game version -> lib/mc/vNNN/mc_rcp_vNNN.fi.

Source: minecraft-data recipes.json (shaped `inShape` + shapeless `ingredients`; tags are already expanded to one recipe per member,
item ids = the ids of items.json = the registry ids of gen_registry.py). Special recipes minecraft-data does not list (banner patterns,
firework, map cloning, armor dyeing, shulker dyeing, book cloning, tipped arrows, repair) are NOT in the table: the server stays the
authority for them (mc_inv shows an empty result and the server's Set Slot corrects it).

BLOB ("RCP1"; every number is 2 octets of 7 bits = 0..16383, `ln` = 1 octet < 128):
    "RCP1", n_entries (2 octets), then n_entries x
      kind (1 octet: 1 shaped, 2 shapeless), a (1 octet: width / ingredient count), b (1 octet: height / 0),
      result item id (2 octets), result count (1 octet), cells (2 octets each: item id + 1, 0 = empty; shaped row by row, w*h cells)
Only recipes that fit into 3x3 are emitted. The reader is lib/mc/mc_craft.fi.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen_registry as gr  # noqa: E402


def n14(v):
    assert 0 <= v < (1 << 14), v
    return bytes([(v >> 7) & 0x7F, v & 0x7F])


def build(data_dir, version):
    paths = json.load(open(os.path.join(data_dir, "dataPaths.json")))["pc"]
    vt = json.load(open(os.path.join(HERE, "versions.json")))["versions"]
    key = vt[version]["data"] if version in vt else version
    P = paths[key]
    rec = json.load(open(os.path.join(data_dir, P["recipes"], "recipes.json")))
    items = json.load(open(os.path.join(data_dir, P["items"], "items.json")))
    ids = set(i["id"] for i in items)
    out = bytearray()
    n = 0
    skipped = 0
    # recipe order = ascending result id, then file order (minecraft-data keeps the vanilla order within a result)
    for rk in sorted(rec, key=lambda k: int(k)):
        for e in rec[rk]:
            res = e["result"]
            rid, rc = res["id"], res["count"]
            if rid not in ids or not (1 <= rc < 128):
                skipped += 1
                continue
            if "inShape" in e:
                shape = e["inShape"]
                h = len(shape)
                w = max(len(r) for r in shape) if h else 0
                if h == 0 or w == 0 or w > 3 or h > 3:
                    skipped += 1
                    continue
                cells = []
                ok = True
                for r in shape:
                    r = list(r) + [None] * (w - len(r))
                    for x in r:
                        if x is None:
                            cells.append(0)
                        elif isinstance(x, int) and x in ids:
                            cells.append(x + 1)
                        else:
                            ok = False
                if not ok:
                    skipped += 1
                    continue
                out += bytes([1, w, h]) + n14(rid) + bytes([rc])
                for c in cells:
                    out += n14(c)
            else:
                ing = e["ingredients"]
                if not (1 <= len(ing) <= 9) or not all(isinstance(x, int) and x in ids for x in ing):
                    skipped += 1
                    continue
                out += bytes([2, len(ing), 0]) + n14(rid) + bytes([rc])
                for x in ing:
                    out += n14(x + 1)
            n += 1
    return b"RCP1" + n14(n) + bytes(out), n, skipped, key


def generate(data_dir, version, pver, out_path):
    blob, n, skipped, key = build(data_dir, version)
    L = ["// SPDX-License-Identifier: MPL-2.0", "// GENERATED by tools/mcgen/gen_recipes.py - do not edit", "//",
         "// lib/mc/v%s/mc_rcp_v%s.fi -- crafting recipes of Minecraft Java %s (protocol %s): %d recipes (%d octets)." % (pver, pver, version, pver, n, len(blob)),
         "// Source: minecraft-data data/%s recipes.json (tags expanded; special recipes are left to the server). The reader is lib/mc/mc_craft.fi." % key,
         "", "import mc.mc_craft", "", 'const RCP_BLOB: str = "%s"' % gr.lit_string(blob), "",
         "fn recipes_make() -> mc_craft.Recipes {", "    return mc_craft.craft_open(RCP_BLOB.p as u64)", "}"]
    open(out_path, "w").write("\n".join(L) + "\n")
    sys.stderr.write("gen_recipes: %s: %d recipes (%d skipped) blob %d octets\n" % (version, n, skipped, len(blob)))


def main():
    if len(sys.argv) != 5:
        raise SystemExit(__doc__)
    data_dir, version, pver, out_path = sys.argv[1:5]
    generate(data_dir, version, pver, out_path)


if __name__ == "__main__":
    main()
