"""gen_sounds.py -- minecraft-data sounds.json (sound registry: id -> name) -> a Firn module per version.

usage: gen_sounds.py <minecraft-data-data-dir> <version> <out.fi>
       gen_sounds.py --all <minecraft-data-data-dir> <libdir> [all|v1,v2,...]

Emits lib/mc/vNNN/mc_snd_vNNN.fi: the NAMES of the sound events (only names, no audio, nothing of the game files)
as one string literal blob, `name\\0name\\0...` in registry order, plus SND_COUNT and SND_FIRST (the registry id
of entry 0). A version without sounds.json (1.8.9 plays sounds by name only) gets an empty table.
The loader is mc_audio.mca_sound_table_load(m, SND_BLOB.p, SND_COUNT, SND_FIRST).
Version = data: a new game version is this script run with another version string (versions.json 'data' key,
optional 'sound_id_shift' = registry id minus minecraft-data id).
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def lit_string(blob):
    parts = []
    for b in blob:
        assert b < 0x80
        c = chr(b)
        if c == '"':
            parts.append('\\"')
        elif c == "\\":
            parts.append("\\\\")
        elif 0x20 <= b < 0x7F and c != "{":
            parts.append(c)
        else:
            parts.append("\\x%02x" % b)
    return "".join(parts)


def load_entries(data_dir, version):
    """-> (list of names in id order, first registry id, minecraft-data key)."""
    paths = json.load(open(os.path.join(data_dir, "dataPaths.json")))["pc"]
    vt = json.load(open(os.path.join(HERE, "versions.json")))["versions"]
    meta = vt.get(version, {})
    key = meta.get("data", version)
    shift = meta.get("sound_id_shift", 0)
    P = paths[key]
    if "sounds" not in P:
        return [], 0, key
    src = os.path.join(data_dir, P["sounds"], "sounds.json")
    ents = json.load(open(src))
    ents.sort(key=lambda e: e["id"])
    first = ents[0]["id"]
    for i, e in enumerate(ents):
        assert e["id"] == first + i, "sound ids not contiguous at %s" % e
        assert e["name"] and all(0x20 < ord(c) < 0x7F for c in e["name"]), e
    return [e["name"] for e in ents], first + shift, key


def generate(data_dir, version, out_path, protocol=None):
    names, first, key = load_entries(data_dir, version)
    blob = b"".join(n.encode("ascii") + b"\0" for n in names)
    pv = protocol if protocol is not None else out_path.split("_v")[-1].split(".")[0]
    out = ["// SPDX-License-Identifier: MPL-2.0",
           "// GENERATED by tools/mcgen/gen_sounds.py - do not edit",
           "//",
           "// lib/mc/v%s/mc_snd_v%s.fi -- sound event NAMES of Minecraft Java %s (protocol %s): %d entries, registry ids %d..%d." % (pv, pv, version, pv, len(names), first, first + len(names) - 1 if names else first),
           "// Names only (no audio). Source: minecraft-data (PrismarineJS, MIT) data/%s sounds.json." % key,
           "// Use: mc_audio.mca_sound_table_load(&m, SND_BLOB.p as u64, SND_COUNT, SND_FIRST).",
           "",
           "export { SND_BLOB, SND_COUNT, SND_FIRST }",
           "",
           "const SND_COUNT: usize = %d" % len(names),
           "const SND_FIRST: i32 = %d" % first,
           "const SND_BLOB: str = \"%s\"" % lit_string(blob),
           ""]
    with open(out_path, "w") as fh:
        fh.write("\n".join(out))
    return len(names)


def main():
    if len(sys.argv) >= 4 and sys.argv[1] == "--all":
        data_dir, libdir = sys.argv[2], sys.argv[3]
        vt = json.load(open(os.path.join(HERE, "versions.json")))["versions"]
        want = list(vt) if len(sys.argv) < 5 or sys.argv[4] == "all" else sys.argv[4].split(",")
        for v in want:
            pv = vt[v]["protocol"]
            d = os.path.join(libdir, "v%d" % pv)
            os.makedirs(d, exist_ok=True)
            n = generate(data_dir, v, os.path.join(d, "mc_snd_v%d.fi" % pv), pv)
            print("gen_sounds: %s (protocol %d): %d sounds" % (v, pv, n))
        return
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    generate(sys.argv[1], sys.argv[2], sys.argv[3])


if __name__ == "__main__":
    main()
