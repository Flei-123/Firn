const fs = require('fs')
const path = require('path')
const root = process.argv[2]
const mcver = process.argv[3]
const out = process.argv[4]
const nbt = require(path.join(root, 'prismarine-nbt'))
const login = JSON.parse(fs.readFileSync(path.join(root, 'minecraft-data/minecraft-data/data/pc', mcver, 'loginPacket.json'), 'utf8'))
const codec = login.dimensionCodec
const bytes = nbt.writeUncompressed(codec, 'big')
const biomes = codec.value['minecraft:worldgen/biome'].value.value.value.value
let plains = 0
for (const e of biomes) {
  if (e.name.value === 'minecraft:plains') plains = e.id.value
}
const lines = [
  '// SPDX-License-Identifier: MPL-2.0',
  '// GENERATED by tools/mcgen/gen_login_codec.cjs - do not edit',
  '',
  'export { CODEC_VALUE, BIOME_PLAINS }',
  '',
  'const BIOME_PLAINS: i32 = ' + plains,
  'const CODEC_VALUE: str = "hex:' + Buffer.from(bytes).toString('hex') + '"',
  ''
]
fs.writeFileSync(out, lines.join('\n'))
console.log('codec ' + bytes.length + ' octets, plains id ' + plains)
