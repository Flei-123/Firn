import json
import struct
import sys

SKIP_IDS = {0x0F, 0x03}


def read_varint(b, at):
    r = 0
    shift = 0
    while True:
        x = b[at]
        at += 1
        r |= (x & 127) << shift
        if not x & 128:
            return r, at
        shift += 7


def read_string(b, at):
    n, at = read_varint(b, at)
    return b[at:at + n].decode("utf8"), at + n


def skip_payload(b, at, tag):
    if tag == 1:
        return at + 1
    if tag == 2:
        return at + 2
    if tag == 3 or tag == 5:
        return at + 4
    if tag == 4 or tag == 6:
        return at + 8
    if tag == 7:
        n = struct.unpack(">i", b[at:at + 4])[0]
        return at + 4 + n
    if tag == 8:
        n = struct.unpack(">H", b[at:at + 2])[0]
        return at + 2 + n
    if tag == 9:
        inner = b[at]
        n = struct.unpack(">i", b[at + 1:at + 5])[0]
        at += 5
        for _ in range(n):
            at = skip_payload(b, at, inner)
        return at
    if tag == 10:
        while b[at] != 0:
            t = b[at]
            n = struct.unpack(">H", b[at + 1:at + 3])[0]
            at = skip_payload(b, at + 3 + n, t)
        return at + 1
    if tag == 11:
        n = struct.unpack(">i", b[at:at + 4])[0]
        return at + 4 + 4 * n
    if tag == 12:
        n = struct.unpack(">i", b[at:at + 4])[0]
        return at + 4 + 8 * n
    raise ValueError("nbt tag %d" % tag)


def registry_keys(body):
    reg, at = read_string(body, 0)
    n, at = read_varint(body, at)
    keys = []
    for _ in range(n):
        key, at = read_string(body, at)
        present = body[at]
        at += 1
        if present:
            at = skip_payload(body, at + 1, body[at])
        keys.append(key)
    return reg, keys


def main():
    cap = json.load(open(sys.argv[1]))
    out = sys.argv[2]
    packets = []
    biome_plains = -1
    biome_count = 0
    dim_overworld = -1
    for p in cap["config"]:
        if p["id"] in SKIP_IDS:
            continue
        body = bytes.fromhex(p["body"])
        if p["id"] == 7:
            reg, keys = registry_keys(body)
            if reg == "minecraft:worldgen/biome":
                biome_plains = keys.index("minecraft:plains")
                biome_count = len(keys)
            if reg == "minecraft:dimension_type":
                dim_overworld = keys.index("minecraft:overworld")
        packets.append((p["id"], body))
    if biome_plains < 0 or dim_overworld < 0:
        raise SystemExit("plains or overworld missing")
    lines = [
        "// SPDX-License-Identifier: MPL-2.0",
        "// GENERATED by tools/mcgen/gen_cfg_v777.py - do not edit",
        "",
        "export { CFG_COUNT, BIOME_PLAINS, BIOME_COUNT, DIM_OVERWORLD, cfg_id, cfg_hex }",
        "",
        "const CFG_COUNT: usize = %d" % len(packets),
        "const BIOME_PLAINS: i32 = %d" % biome_plains,
        "const BIOME_COUNT: i32 = %d" % biome_count,
        "const DIM_OVERWORLD: i32 = %d" % dim_overworld,
        "",
    ]
    for i, (pid, body) in enumerate(packets):
        lines.append('const CFG_%02d: str = "%s"' % (i, body.hex()))
    lines.append("")
    lines.append("fn cfg_id(i: usize) -> i32 {")
    for i, (pid, body) in enumerate(packets):
        lines.append("    if i == %d { return %d }" % (i, pid))
    lines.append("    return 0 - 1")
    lines.append("}")
    lines.append("")
    lines.append("fn cfg_hex(i: usize) -> str {")
    for i, (pid, body) in enumerate(packets):
        lines.append("    if i == %d { return CFG_%02d }" % (i, i))
    lines.append('    return ""')
    lines.append("}")
    lines.append("")
    open(out, "w").write("\n".join(lines))
    print("packets", len(packets), "plains", biome_plains, "biomes", biome_count, "overworld", dim_overworld)


main()
