"""gen_attr.py -- attribute registry names per protocol -> lib/mc/mc_attr.fi.

Attribute modifiers on an item carry the numeric id of the attribute (a built-in registry, NOT synced in the configuration phase), but the hash of
the hashed stack (1.21.5+) is over the registry KEY ("minecraft:attack_damage"). The order of minecraft-data's attributes.json is the registry order.
Usage: gen_attr.py <minecraft-data/data dir> <out .fi>   (protocols 770 772 774 775 = 1.21.5, 1.21.8, 1.21.11, 26.1)
"""
import json
import os
import sys

TARGETS = [(770, "1.21.5"), (772, "1.21.8"), (774, "1.21.11"), (775, "26.1")]


def main():
    data, out = sys.argv[1], sys.argv[2]
    lists = []
    for proto, ver in TARGETS:
        path = os.path.join(data, "pc", ver, "attributes.json")
        names = [a["resource"] for a in json.load(open(path))]
        for i, n in enumerate(names):
            assert n.startswith("minecraft:"), n
        lists.append((proto, "\\n".join(names)))
    o = ["// SPDX-License-Identifier: MPL-2.0",
         "// lib/mc/mc_attr.fi -- GENERATED by tools/mcgen/gen_attr.py (do not edit): attribute registry keys per protocol, one name per line, index = registry id.",
         "export { attr_name }", ""]
    for proto, txt in lists:
        o.append(f'const ATTR_{proto}: str = "{txt}"')
    o += ["", "// pointer + length of the key of attribute `id` (length 0 = unknown id or protocol)",
          "fn attr_name(protocol: i32, id: i32, len: *mut usize) -> u64 {",
          "    *len = 0",
          "    if id < 0 { return 0 }"]
    for i, (proto, txt) in enumerate(lists):
        cond = f"protocol == {proto}"
        o.append(f"    if {cond} {{ return attr_pick(ATTR_{proto}.p as u64, ATTR_{proto}.n, id, len) }}")
    o += ["    return 0", "}", "",
          "fn attr_pick(p: u64, n: usize, id: i32, len: *mut usize) -> u64 {",
          "    var line: i32 = 0",
          "    var i: usize = 0",
          "    var start: usize = 0",
          "    while i <= n {",
          "        if i == n || rt.ld8(p, i) == 10 as u8 {",
          "            if line == id { *len = i - start; return p + (start as u64) }",
          "            line = line + 1",
          "            start = i + 1",
          "        }",
          "        i = i + 1",
          "    }",
          "    return 0", "}", ""]
    src = "\n".join(o)
    src = src.replace("export { attr_name }\n", "import std.rt\n\nexport { attr_name }\n", 1)
    open(out, "w").write(src)


main()
