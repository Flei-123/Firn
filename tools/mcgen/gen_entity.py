"""gen_entity.py -- entity packet layouts per protocol version -> lib/mc/mc_entity_layout.fi.

The entity tracker (lib/mc/mc_entity.fi) reads the PREFIX of a few play packets (spawn, move,
look, teleport, destroy, velocity). Which fields come in which order and with which wire type
differs per version (1.8: i32 fixed point, 1.9+: f64, deltas i8 -> i16, ...), so the layout is
generated from minecraft-data's protocol.json instead of being written by hand per version.

A layout is a text program of 2-character tokens (role, type):

  role   E entity id           U uuid           T entity/object type      X Y Z absolute position
         x y z relative move   W yaw            P pitch                   G on ground
         M velocity (type V)   -  skipped field  A array of entity ids (type v), always alone
  type   v varint  b i8  B u8  s i16  i i32  d f64  f f32  u uuid(16)  o bool  V vec3i16 (6 octets)  L lpVec3 (1.21.9+, skipped only)

Reading stops after the last wanted role: trailing fields (metadata, head pitch, object data)
are never touched. The interpreter gives the types their meaning:
  X Y Z with i -> fixed point /32 (1.8),  with d -> block units
  x y z with b -> /32 (1.8),              with s -> /4096 (1.9+)
  W P   with b -> angle byte * 360 / 256, with f -> degrees
A field of a type the interpreter does not know before the last wanted role makes this
generator FAIL (never a silent wrong layout).
"""
import json
import os

KINDS = [  # (kind constant, semantic name list in minecraft-data, packet fields wanted)
    ("SPAWN_OBJECT", ["spawn_entity"]),
    ("SPAWN_LIVING", ["spawn_entity_living"]),
    ("SPAWN_PLAYER", ["named_entity_spawn"]),
    ("TELEPORT", ["entity_teleport"]),
    ("REL_MOVE", ["rel_entity_move"]),
    ("MOVE_LOOK", ["entity_move_look"]),
    ("LOOK", ["entity_look"]),
    ("DESTROY", ["entity_destroy"]),
    ("VELOCITY", ["entity_velocity"]),
    ("SYNC_POSITION", ["sync_entity_position"]),
]

ROLE = {
    "entityId": "E", "objectUUID": "U", "entityUUID": "U", "playerUUID": "U", "type": "T",
    "x": "X", "y": "Y", "z": "Z", "yaw": "W", "pitch": "P", "onGround": "G",
}
ROLE_REL = {"dX": "x", "dY": "y", "dZ": "z"}
TYPE = {"varint": "v", "i8": "b", "u8": "B", "i16": "s", "i32": "i", "f64": "d", "f32": "f",
        "UUID": "u", "bool": "o", "vec3i16": "V", "lpVec3": "L"}


def layout_of(proto, names, move):
    """The token program of the first existing packet of `names`, or '' when the version has none."""
    types = proto["play"]["toClient"]["types"]
    for n in names:
        t = types.get("packet_" + n)
        if t is None:
            continue
        assert t[0] == "container", n
        fields = t[1]
        if n == "entity_destroy":
            f = fields[0]
            ty = f["type"]
            assert f["name"] == "entityIds" and ty[0] == "array" and ty[1]["countType"] == "varint" \
                and ty[1]["type"] == "varint", "entity_destroy layout changed: " + json.dumps(f)
            return "Av"
        toks = []
        for f in fields:
            fn, ft = f["name"], f["type"]
            role = ROLE_REL.get(fn) if move else None
            if role is None:
                role = ROLE.get(fn, "-")
            if n == "entity_velocity" and fn == "velocity":
                role = "M"
            if not isinstance(ft, str) or ft not in TYPE:
                toks.append((role, None, fn, ft))
            else:
                toks.append((role, TYPE[ft], fn, ft))
        last = max(i for i, t in enumerate(toks) if t[0] != "-")
        out = []
        for role, ty, fn, ft in toks[: last + 1]:
            if ty is None:
                raise SystemExit("gen_entity: %s.%s has type %s before the last wanted field" % (n, fn, json.dumps(ft)))
            out.append(role + ty)
        return "".join(out)
    return ""


def generate(data_dir, versions, load_protocol, out_path):
    entries = []
    for vkey in versions:
        proto, pver, _ = load_protocol(data_dir, vkey)
        progs = []
        for kname, names in KINDS:
            move = kname in ("REL_MOVE", "MOVE_LOOK")
            progs.append(layout_of(proto, names, move))
        entries.append((pver, vkey, progs))
    w = []
    a = w.append
    a("// SPDX-License-Identifier: MPL-2.0")
    a("// GENERATED by tools/mcgen/gen_entity.py from minecraft-data - do not edit")
    a("//")
    a("// lib/mc/mc_entity_layout.fi -- the field layout of the entity packets per protocol version.")
    a("// Token program format: tools/mcgen/gen_entity.py (docs/mc/entity.md). `layout` returns the")
    a("// empty string when the version has no such packet.")
    a("")
    a("export { layout, KIND_COUNT, " + ", ".join("KIND_" + k for k, _ in KINDS) + " }")
    a("")
    a("const KIND_COUNT: usize = %d" % len(KINDS))
    for i, (k, _) in enumerate(KINDS):
        a("const KIND_%s: usize = %d" % (k, i))
    a("")
    for pver, vkey, progs in entries:
        for i, p in enumerate(progs):
            a('const L_%d_%d: str = "%s"' % (pver, i, p))
    a("")
    a('const L_NONE: str = ""')
    a("")
    a("// layout program of kind `k` (KIND_*) for `protocol`; empty when unknown")
    a("fn layout(protocol: i32, k: usize) -> str {")
    for pver, vkey, progs in entries:
        a("    if protocol == %d {" % pver)
        for i, p in enumerate(progs):
            a("        if k == %d {" % i)
            a("            return L_%d_%d" % (pver, i))
            a("        }")
        a("    }")
    a("    return L_NONE")
    a("}")
    with open(out_path, "w") as fh:
        fh.write("\n".join(w) + "\n")
