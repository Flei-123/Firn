#!/usr/bin/env python3
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "lib", "mc", "mc_supported.fi")
STATUSES = ("joinable", "tables_only")


def fi_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def load():
    supported = json.load(open(os.path.join(HERE, "supported.json")))["versions"]
    facts = json.load(open(os.path.join(HERE, "versions.json")))["versions"]
    seen = set()
    for name, e in supported.items():
        if e["status"] not in STATUSES:
            raise SystemExit("bad status for " + name)
        if name not in facts or facts[name]["protocol"] != e["protocol"]:
            raise SystemExit("version " + name + " is not in versions.json with protocol " + str(e["protocol"]))
        if e["status"] == "tables_only" and (e["client"] or e["server"]):
            raise SystemExit("tables_only entry with client/server flag: " + name)
        for key in [name] + e.get("aliases", []):
            if key in seen:
                raise SystemExit("duplicate name or alias " + key)
            seen.add(key)
    return supported


def joinable_json(supported):
    items = []
    for name, e in supported.items():
        if e["status"] != "joinable":
            continue
        aliases = ",".join(json.dumps(a) for a in e.get("aliases", []))
        items.append('{"name":%s,"protocol":%d,"aliases":[%s],"client":%s,"server":%s}' % (
            json.dumps(name), e["protocol"], aliases, str(e["client"]).lower(), str(e["server"]).lower()))
    return '{"versions":[' + ",".join(items) + "]}"


def switch(fn, ret, rows, default):
    lines = ["fn %s(i: usize) -> %s {" % (fn, ret)]
    for i, value in enumerate(rows):
        lines.append("    if i == %d { return %s }" % (i, value))
    lines.append("    return %s\n}\n" % default)
    return "\n".join(lines)


def render(supported):
    names = list(supported.keys())
    entries = [supported[n] for n in names]
    out = [
        "// SPDX-License-Identifier: MPL-2.0",
        "// GENERATED by tools/mcgen/gen_supported.py from tools/mcgen/supported.json - do not edit",
        "",
        "import std.rt",
        "",
        "export { supported_count, supported_name_at, supported_protocol_at, supported_joinable_at, supported_client_at, supported_server_at, supported_protocol_by_name, JOINABLE_JSON }",
        "",
        "const JOINABLE_JSON: str = " + fi_string(joinable_json(supported)),
        "",
        "fn supported_count() -> usize { return %d }\n" % len(names),
        switch("supported_name_at", "str", [fi_string(n) for n in names], '""'),
        switch("supported_protocol_at", "i32", [str(e["protocol"]) for e in entries], "0 - 1"),
        switch("supported_joinable_at", "bool", [str(e["status"] == "joinable").lower() for e in entries], "false"),
        switch("supported_client_at", "bool", [str(e["client"]).lower() for e in entries], "false"),
        switch("supported_server_at", "bool", [str(e["server"]).lower() for e in entries], "false"),
        "fn name_is(a: str, b: str) -> bool {\n    return a.n == b.n && rt.mem_eq(a.p as u64, b.p as u64, a.n)\n}\n",
        "fn supported_protocol_by_name(name: str) -> i32 {",
    ]
    for n, e in supported.items():
        for key in [n] + e.get("aliases", []):
            out.append("    if name_is(name, %s) { return %d }" % (fi_string(key), e["protocol"]))
    out.append("    return 0 - 1\n}")
    return "\n".join(out) + "\n"


def main():
    text = render(load())
    if len(sys.argv) == 2 and sys.argv[1] == "--check":
        if open(OUT).read() != text:
            raise SystemExit("lib/mc/mc_supported.fi is stale: run python3 tools/mcgen/gen_supported.py")
        return
    open(OUT, "w").write(text)


main()
