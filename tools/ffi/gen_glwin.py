#!/usr/bin/env python3
# SPDX-License-Identifier: MPL-2.0
# Generates lib/plat/glwin.fi (fUi's GL table for Windows) out of
# lib/plat/gles.fi: every `extern fn glName(...)` of the Android table becomes
# a small function of the same name and signature that looks the GL function
# up once (gpu.wgl.proc: wglGetProcAddress, then opengl32.dll) and calls it
# through the Win64 gate -- so the rest of the file (the table, the shader
# helper) stays the SAME text as for Android, and no compiler import list
# needs a new entry (GAPS B16).
#
#   python3 tools/ffi/gen_glwin.py > lib/plat/glwin.fi
import re
import sys
import os

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
src = open(os.path.join(root, "lib", "plat", "gles.fi")).read().split("\n")

ext = re.compile(r"^extern fn (gl\w+)\((.*)\)(?: -> (\w+))?;\s*$")
HEADER = """// SPDX-License-Identifier: MPL-2.0
// lib/plat/glwin.fi -- THE GPU OF A WINDOWS PC for fUi: desktop OpenGL (3.3 core)
// out of opengl32.dll, through lib/gpu/wgl.windows.fi.
//
// GENERATED by tools/ffi/gen_glwin.py from lib/plat/gles.fi -- do not edit by
// hand. Only the `extern fn` lines differ from gles.fi: here each is a wrapper
// that finds the GL function with wglGetProcAddress / opengl32 and calls it
// through the Win64 gate, so no import list in the compiler needs an entry
// (GAPS B16). The table and the shader helper are the same text as for Android.
// Windows only. NOT TESTED ON REAL WINDOWS (Wine + Mesa llvmpipe only)."""
out = HEADER.split("\n")
wrappers = []
idx = 0
started = False
for line in src:
    if not started:
        if line.startswith("import std.rt"):
            started = True
        else:
            continue
    m = ext.match(line)
    if not m:
        if line.startswith("import paint.gl"):
            out.append(line)
            out.append("import gpu.wgl")
            continue
        if line.startswith("export {"):
            out.append("export { gles_api, glwin_api, glwin_reset }")
            out.append("@@HELPER@@")
            continue
        out.append(line)
        continue
    name, args, ret = m.group(1), m.group(2).strip(), m.group(3)
    params = [a.strip() for a in args.split(",")] if args else []
    names = [p.split(":")[0].strip() for p in params]
    n = len(names)
    if n > 10:
        sys.exit("too many args: " + name)
    call_args = "".join(", %s as u64" % x for x in names)
    call = "wgl.call%d(fnp(%d, \"%s\")%s)" % (n, idx, name, call_args)
    sig = "fn %s(%s)" % (name, args)
    if ret:
        out.append("%s -> %s { return %s as %s }" % (sig, ret, call, ret))
    else:
        out.append("%s { %s }" % (sig, call))
    idx += 1
if idx > 64:
    sys.exit("more than 64 GL functions: enlarge G_FN")

text = "\n".join(out)
# the cache and its helper go right after the import lines
helper = """
// GL function addresses, found on first use.
static mut G_FN: [u64; 64] = [0; 64]

fn fnp(i: usize, name: str) -> u64 {
    let f: u64 = G_FN[i]
    if f != 0 {
        return f
    }
    let a: u64 = wgl.proc(name)
    G_FN[i] = a
    return a
}

// Forget the cached addresses (a new context may hand out new ones).
fn glwin_reset() {
    var i: usize = 0
    while i < 64 {
        G_FN[i] = 0
        i = i + 1
    }
}

// The desktop table: the same entries as gles_api, after checking that the
// context really has the GL 3.x calls fUi needs (VAO, instancing, FBO blit).
// ok stays false otherwise, and the caller falls back to memory painting.
fn glwin_api(t: *mut gl.GlApi) -> bool {
    glwin_reset()
    if wgl.proc("glGenVertexArrays") == 0 || wgl.proc("glDrawArraysInstanced") == 0 ||
    wgl.proc("glBlitFramebuffer") == 0 || wgl.proc("glClearBufferfv") == 0 ||
    wgl.proc("glVertexAttribDivisor") == 0 || wgl.proc("glCreateShader") == 0 {
        *t = gl.gl_api_new()
        return false
    }
    gles_api(t)
    return true
}
"""
text = text.replace("@@HELPER@@", helper.strip("\n"), 1)
sys.stdout.write(text + ("" if text.endswith("\n") else "\n"))
