#!/usr/bin/env python3
"""tools/input/gen_compose.py -- generates lib/input/composedata.fi.

Two tables, both sorted for binary search:
  DEAD_*  dead key + base letter -> precomposed code point (Unicode NFC of base + the combining mark, so it is
          exactly as complete as Python's unicodedata (UCD 14); only single code point results are kept)
  SEQ_*   Compose-key sequences (Multi_key k1 k2 [k3]) for ASCII keys, from the X11 locale file
          /usr/share/X11/locale/en_US.UTF-8/Compose, single code point results only
Usage: python3 -I tools/input/gen_compose.py [Compose-file] > lib/input/composedata.fi
"""
import re
import sys
import unicodedata

compose_path = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/X11/locale/en_US.UTF-8/Compose"

# dead keysym -> (combining mark, spacing form)
DEAD = [
    (0xFE50, 0x0300, 0x0060), (0xFE51, 0x0301, 0x00B4), (0xFE52, 0x0302, 0x005E), (0xFE53, 0x0303, 0x007E),
    (0xFE54, 0x0304, 0x00AF), (0xFE55, 0x0306, 0x02D8), (0xFE56, 0x0307, 0x02D9), (0xFE57, 0x0308, 0x00A8),
    (0xFE58, 0x030A, 0x02DA), (0xFE59, 0x030B, 0x02DD), (0xFE5A, 0x030C, 0x02C7), (0xFE5B, 0x0327, 0x00B8),
    (0xFE5C, 0x0328, 0x02DB), (0xFE60, 0x0323, 0x0323), (0xFE61, 0x0309, 0x0309), (0xFE62, 0x031B, 0x031B),
]

dead_keys = []
for di, (_, mark, _) in enumerate(DEAD):
    for base in list(range(0x20, 0x250)) + list(range(0x370, 0x400)) + list(range(0x400, 0x500)):
        if base == 0x20:
            continue
        n = unicodedata.normalize("NFC", chr(base) + chr(mark))
        if len(n) == 1 and ord(n) != base:
            dead_keys.append((di * 0x200000 + base, ord(n)))
dead_keys.sort()

NAMES = {
    "space": " ", "exclam": "!", "quotedbl": '"', "numbersign": "#", "dollar": "$", "percent": "%", "ampersand": "&",
    "apostrophe": "'", "parenleft": "(", "parenright": ")", "asterisk": "*", "plus": "+", "comma": ",", "minus": "-",
    "period": ".", "slash": "/", "colon": ":", "semicolon": ";", "less": "<", "equal": "=", "greater": ">",
    "question": "?", "at": "@", "bracketleft": "[", "backslash": "\\", "bracketright": "]", "asciicircum": "^",
    "underscore": "_", "grave": "`", "braceleft": "{", "bar": "|", "braceright": "}", "asciitilde": "~",
}
for c in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789":
    NAMES[c] = c

seqs = {}
line_re = re.compile(r'^<Multi_key>((?:\s+<[A-Za-z0-9_]+>){2,3})\s*:\s*"((?:[^"\\]|\\.)*)"')
for line in open(compose_path, encoding="utf-8"):
    m = line_re.match(line)
    if not m:
        continue
    keys = re.findall(r"<([A-Za-z0-9_]+)>", m.group(1))
    if any(k not in NAMES for k in keys):
        continue
    res = m.group(2)
    if res.startswith("\\"):
        res = {"\\\\": "\\", '\\"': '"'}.get(res, res)
    if len(res) != 1:
        continue
    cps = [ord(NAMES[k]) for k in keys] + [0] * (3 - len(keys))
    key = (cps[0] << 14) | (cps[1] << 7) | cps[2]
    seqs.setdefault(key, ord(res))
seq_items = sorted(seqs.items())


def arr(name, vals, ty="u32"):
    out = ["static %s: [%s; %d] = [" % (name, ty, len(vals))]
    line = "   "
    for v in vals:
        s = " %d," % v
        if len(line) + len(s) > 118:
            out.append(line)
            line = "   "
        line += s
    out.append(line)
    out.append("]")
    return "\n".join(out)


print("// SPDX-License-Identifier: MPL-2.0")
print("// lib/input/composedata.fi -- GENERATED by tools/input/gen_compose.py. Do not edit.")
print("// DEAD_KEY: dead key index * 0x200000 + base code point (sorted); DEAD_RES: the precomposed code point.")
print("// SEQ_KEY: (k1 << 14) | (k2 << 7) | k3 of a Compose-key sequence (k3 = 0 for two keys, sorted); SEQ_RES: result.")
print("// Dead keys (index): grave acute circumflex tilde macron breve abovedot diaeresis abovering doubleacute caron")
print("// cedilla ogonek belowdot hook horn = keysyms 0xFE50..0xFE5C, 0xFE60..0xFE62.")
print("export { DEAD_KEY, DEAD_RES, DEAD_N, SEQ_KEY, SEQ_RES, SEQ_N, DEAD_SYM, DEAD_SPACING }")
print()
print("const DEAD_N: usize = %d" % len(dead_keys))
print("const SEQ_N: usize = %d" % len(seq_items))
print(arr("DEAD_SYM", [d[0] for d in DEAD]))
print(arr("DEAD_SPACING", [d[2] for d in DEAD]))
print(arr("DEAD_KEY", [k for k, _ in dead_keys]))
print(arr("DEAD_RES", [r for _, r in dead_keys]))
print(arr("SEQ_KEY", [k for k, _ in seq_items]))
print(arr("SEQ_RES", [r for _, r in seq_items]))
