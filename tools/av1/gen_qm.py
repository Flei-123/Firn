import re
import sys

KEYS = [(4, 4), (8, 8), (16, 16), (32, 32), (4, 8), (8, 4), (8, 16), (16, 8), (16, 32), (32, 16), (4, 16), (16, 4), (8, 32), (32, 8)]
TOTAL = sum(w * h for w, h in KEYS)


def parse(path):
    text = open(path).read()
    tables = {}
    for m in re.finditer(r"static const uint8_t qm_tbl_(\d+)x(\d+)\[[^\]]*\]\[2\]\[(\d+)\] = \{(.*?)\n\};", text, re.S):
        h, w = int(m.group(1)), int(m.group(2))
        nums = [int(x) for x in re.findall(r"\d+", m.group(4))]
        n = int(m.group(3))
        assert len(nums) == 15 * 2 * n, (h, w, len(nums))
        tables[(h, w)] = [[nums[(lv * 2 + p) * n:(lv * 2 + p + 1) * n] for p in range(2)] for lv in range(15)]
    return tables


def spec_table(tables, lv, p, tw, th):
    src = tables[(th, tw)][lv][p]
    return [src[j * th + i] for i in range(th) for j in range(tw)]


def main():
    tables = parse(sys.argv[1])
    out = sys.argv[2]
    groups = [(0, 5), (5, 10), (10, 15)]
    for gi, (a, b) in enumerate(groups):
        vals = []
        for lv in range(a, b):
            for p in range(2):
                blk = []
                for tw, th in KEYS:
                    blk += spec_table(tables, lv, p, tw, th)
                assert len(blk) == TOTAL
                vals += blk
        lines = []
        for i in range(0, len(vals), 32):
            lines.append("    " + ", ".join(str(v) for v in vals[i:i + 32]))
        name = "av1qm%d" % gi
        with open("%s/%s.fi" % (out, name), "w") as f:
            f.write("// SPDX-License-Identifier: MPL-2.0\n")
            f.write("// lib/av1/%s.fi -- AV1 quantizer matrices, levels %d to %d (generated by tools/av1/gen_qm.py).\n" % (name, a, b - 1))
            f.write("export { base }\n\n")
            f.write("static QM: [u8; %d] = [\n" % len(vals))
            f.write(",\n".join(lines))
            f.write("\n]\n\n")
            f.write("fn base() -> u64 {\n    return (&QM[0]) as u64\n}\n")
    print(TOTAL)


main()
