"""tools/av1/gen_tabs2.py <spec2.txt> <out.fi> -- the transform-size / coefficient-context tables of the lossy intra decoder
(lib/av1/av1tab2.fi) cut from the AV1 specification text (tables are numeric facts of the format).
Never pipe the output through `head` (SIGPIPE)."""
import re, sys

BLOCKS = ["4X4", "4X8", "8X4", "8X8", "8X16", "16X8", "16X16", "16X32", "32X16", "32X32", "32X64", "64X32", "64X64", "64X128",
          "128X64", "128X128", "4X16", "16X4", "8X32", "32X8", "16X64", "64X16"]
TXS = ["4X4", "8X8", "16X16", "32X32", "64X64", "4X8", "8X4", "8X16", "16X8", "16X32", "32X16", "32X64", "64X32", "4X16", "16X4",
       "8X32", "32X8", "16X64", "64X16"]
TXT = ["DCT_DCT", "ADST_DCT", "DCT_ADST", "ADST_ADST", "FLIPADST_DCT", "DCT_FLIPADST", "FLIPADST_FLIPADST", "ADST_FLIPADST",
       "FLIPADST_ADST", "IDTX", "V_DCT", "H_DCT", "V_ADST", "H_ADST", "V_FLIPADST", "H_FLIPADST"]
CONST = {"SIG_COEF_CONTEXTS_2D": 26}

def table(txt, name):
    m = re.search(r"^" + re.escape(name) + r"\s*\[[^=]*=\s*\{", txt, re.M)
    if not m:
        sys.exit("table not found: " + name)
    i = m.end()
    depth = 1
    j = i
    while depth:
        c = txt[j]
        depth += (c == "{") - (c == "}")
        j += 1
    body = re.sub(r"//[^\n]*", "", txt[i:j - 1])
    out = []
    for t in re.findall(r"-?\d+|[A-Z][A-Z0-9_]*(?:\s*\+\s*\d+)?", body):
        if re.fullmatch(r"-?\d+", t):
            out.append(int(t))
        elif t.startswith("BLOCK_"):
            out.append(BLOCKS.index(t[6:]) if t[6:] in BLOCKS else 22)
        elif t.startswith("TX_") and t[3:] in TXS:
            out.append(TXS.index(t[3:]))
        elif t in TXT:
            out.append(TXT.index(t))
        elif re.match(r"SIG_COEF_CONTEXTS_2D", t):
            out.append(26 + (int(t.split("+")[1]) if "+" in t else 0))
        else:
            sys.exit("unknown token %r in %s" % (t, name))
    return out

def main():
    txt = open(sys.argv[1]).read()
    tabs = [("SQR", "t_sqr", "Tx_Size_Sqr"), ("SQRUP", "t_sqrup", "Tx_Size_Sqr_Up"), ("TXW", "t_txw", "Tx_Width"),
            ("TXH", "t_txh", "Tx_Height"), ("TXWL", "t_txwl", "Tx_Width_Log2"), ("TXHL", "t_txhl", "Tx_Height_Log2"),
            ("ADJ", "t_adj", "Adjusted_Tx_Size"), ("SPLIT", "t_split", "Split_Tx_Size"), ("MAXRECT", "t_maxrect", "Max_Tx_Size_Rect"),
            ("MAXDEPTH", "t_maxdepth", "Max_Tx_Depth"), ("M2T", "t_mode2tx", "Mode_To_Txfm"),
            ("CBCTX", "t_cbctx", "Coeff_Base_Ctx_Offset"), ("SIGREF", "t_sigref", "Sig_Ref_Diff_Offset"),
            ("MAGREF", "t_magref", "Mag_Ref_Offset_With_Tx_Class"), ("CBPOS", "t_cbpos", "Coeff_Base_Pos_Ctx_Offset"),
            ("INSET", "t_inset", "Tx_Type_In_Set_Intra"), ("INV1", "t_inv1", "Tx_Type_Intra_Inv_Set1"),
            ("INV2", "t_inv2", "Tx_Type_Intra_Inv_Set2")]
    names = ", ".join(t[1] for t in tabs) + ", t_smw"
    o = ["// SPDX-License-Identifier: GPL-2.0-only",
         "// lib/av1/av1tab2.fi -- GENERATED by tools/av1/gen_tabs2.py from the AV1 specification text. DO NOT EDIT.",
         "export { %s }" % names, ""]
    def emit(label, vals):
        o.append("static %s: [i16; %d] = [" % (label, len(vals)))
        for k in range(0, len(vals), 16):
            o.append("    " + ", ".join(str(v) for v in vals[k:k + 16]) + ",")
        o.append("]")
        o.append("")
    for lab, fn, spec in tabs:
        emit(lab, table(txt, spec))
    # smooth weights: 4, 8, 16, 32, 64 concatenated; weights for size n start at n (4->4, 8->8, 16->16, 32->32, 64->64) minus 4... use start = n
    smw = []
    starts = {}
    for n in (4, 8, 16, 32, 64):
        starts[n] = len(smw)
        smw += table(txt, "Sm_Weights_Tx_%dx%d" % (n, n))
    emit("SMW", smw)
    for lab, fn, spec in tabs:
        o += ["fn %s(i: i64) -> i64 {" % fn, "    return %s[i as usize] as i64" % lab, "}", ""]
    o += ["// smooth weights of a size-n edge (n = 4..64): index i of the weights for n is t_smw(n, i)",
          "fn t_smw(n: i64, i: i64) -> i64 {"]
    o.append("    var s: i64 = 0")
    for n in (8, 16, 32, 64):
        o.append("    if n == %d {\n        s = %d\n    }" % (n, starts[n]))
    o += ["    return SMW[(s + i) as usize] as i64", "}", ""]
    open(sys.argv[2], "w").write("\n".join(o))

main()
