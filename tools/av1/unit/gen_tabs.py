"""tools/av1/gen_tabs.py <spec2.txt> <out.fi> -- the small AV1 tables of the intra decoder (lib/av1/av1tab.fi) cut from the
AV1 specification text (tables are numeric facts of the format).  Never pipe the output through `head` (SIGPIPE)."""
import re, sys

BLOCKS = ["4X4", "4X8", "8X4", "8X8", "8X16", "16X8", "16X16", "16X32", "32X16", "32X32", "32X64", "64X32", "64X64", "64X128",
          "128X64", "128X128", "4X16", "16X4", "8X32", "32X8", "16X64", "64X16"]

def table(txt, name):
    m = re.search(r"^" + re.escape(name) + r"\s*\[[^=]*=\s*\{", txt, re.M)
    if not m:
        sys.exit("table not found: " + name)
    i = m.end()
    depth = 1
    j = i
    while depth:
        c = txt[j]
        depth += (c == "{") - (c == "}")
        j += 1
    body = txt[i:j - 1]
    out = []
    for t in re.findall(r"-?\d+|BLOCK_[0-9A-Z_]+", body):
        if t.startswith("BLOCK_"):
            k = t[6:]
            out.append(BLOCKS.index(k) if k in BLOCKS else 22)
        else:
            out.append(int(t))
    return out

def emit(o, label, vals):
    o.append("static %s: [i16; %d] = [" % (label, len(vals)))
    for k in range(0, len(vals), 16):
        o.append("    " + ", ".join(str(v) for v in vals[k:k + 16]) + ",")
    o.append("]")
    o.append("")

def main():
    txt = open(sys.argv[1]).read()
    o = ["// SPDX-License-Identifier: GPL-2.0-only",
         "// lib/av1/av1tab.fi -- GENERATED by tools/av1/gen_tabs.py from the AV1 specification text. DO NOT EDIT.",
         "export { t_part_subsize, t_filter_taps, t_dr_deriv, t_cbctx, t_scan4 }", ""]
    emit(o, "PART_SUBSIZE", table(txt, "Partition_Subsize"))
    emit(o, "FILTER_TAPS", table(txt, "Intra_Filter_Taps"))
    emit(o, "DR_DERIV", table(txt, "Dr_Intra_Derivative"))
    emit(o, "CBCTX", table(txt, "Coeff_Base_Ctx_Offset")[:25])
    emit(o, "SCAN4", table(txt, "Default_Scan_4x4"))
    for fn, arr in (("t_part_subsize", "PART_SUBSIZE"), ("t_filter_taps", "FILTER_TAPS"), ("t_dr_deriv", "DR_DERIV"),
                    ("t_cbctx", "CBCTX"), ("t_scan4", "SCAN4")):
        o.append("fn %s(i: i64) -> i64 {" % fn)
        o.append("    return %s[i as usize] as i64" % arr)
        o.append("}")
        o.append("")
    open(sys.argv[2], "w").write("\n".join(o))

main()
