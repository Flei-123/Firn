"""tools/av1/gen_lossy_tabs.py <spec.txt> <out.fi> -- lossy-intra tables of the AV1 decoder (lib/av1/av1lt.fi): coefficient scan
orders (default / mrow / mcol for every tx size that uses them) and the DC/AC quantiser lookups (8/10/12 bit).
Tables are numeric facts of the format cut from the specification text.  Never pipe the output through `head` (SIGPIPE)."""
import re, sys
sys.path.insert(0, __import__("os").path.dirname(__file__))
sys.dont_write_bytecode = True
src = open(__file__.replace("gen_lossy_tabs.py", "gen_tabs.py")).read().replace("\nmain()\n", "\n")
ns = {}
exec(compile(src, "gen_tabs", "exec"), ns)
table = ns["table"]

# tx size order of the spec: TX_4X4 8X8 16X16 32X32 64X64 4X8 8X4 8X16 16X8 16X32 32X16 32X64 64X32 4X16 16X4 8X32 32X8 16X64 64X16
TXN = ["4x4", "8x8", "16x16", "32x32", "64x64", "4x8", "8x4", "8x16", "16x8", "16x32", "32x16", "32x64", "64x32",
       "4x16", "16x4", "8x32", "32x8", "16x64", "64x16"]
# 64-long dimensions code only the 32x32 corner: they use the 32 sized scan
ALIAS = {"64x64": "32x32", "32x64": "32x32", "64x32": "32x32", "16x64": "16x32", "64x16": "32x16"}

def main():
    txt = open(sys.argv[1]).read()
    o = ["// SPDX-License-Identifier: GPL-2.0-only",
         "// lib/av1/av1lt.fi -- GENERATED by tools/av1/gen_lossy_tabs.py from the AV1 specification text. DO NOT EDIT.",
         "export { scan_at, scan_len, dc_q, ac_q }", ""]
    flat = []
    offs = []   # per (txsz, kind) offset into flat, -1 = none ; kind 0 default 1 mrow 2 mcol
    for n in TXN:
        for kind, pre in enumerate(("Default_Scan_", "Mrow_Scan_", "Mcol_Scan_")):
            nm = ALIAS.get(n, n)
            try:
                t = table(txt, pre + nm)
            except SystemExit:
                offs.append(-1)
                continue
            offs.append(len(flat))
            flat += t
    o.append("static SCAN_OFF: [i16; %d] = [%s]" % (len(offs), ", ".join(str(v) for v in offs)))
    o.append("static SCAN_LEN_T: [i16; %d] = [%s]" % (len(TXN), ", ".join(
        str(min(1 << int(a), 32) * min(1 << int(b), 32)) for a, b in (( {"4":2,"8":3,"16":4,"32":5,"64":6}[x.split("x")[0]], {"4":2,"8":3,"16":4,"32":5,"64":6}[x.split("x")[1]]) for x in TXN))))
    o.append("static SCANS: [i16; %d] = [" % len(flat))
    for k in range(0, len(flat), 24):
        o.append("    " + ", ".join(str(v) for v in flat[k:k + 24]) + ",")
    o.append("]")
    o.append("")
    dc = table(txt, "Dc_Qlookup")
    ac = table(txt, "Ac_Qlookup")
    assert len(dc) == 768 and len(ac) == 768, (len(dc), len(ac))
    for nm, v in (("DCQ", dc), ("ACQ", ac)):
        o.append("static %s: [i16; 768] = [" % nm)
        for k in range(0, 768, 16):
            o.append("    " + ", ".join(str(x) for x in v[k:k + 16]) + ",")
        o.append("]")
        o.append("")
    o += ["// scan position `i` (0-based coefficient index in scan order) of tx size `txsz`, scan kind (0 default, 1 mrow, 2 mcol).",
          "// the returned value is the raster position inside the (at most 32x32) coded area, row stride = min(w, 32).",
          "fn scan_at(txsz: i64, kind: i64, i: i64) -> i64 {",
          "    return SCANS[((SCAN_OFF[(txsz * 3 + kind) as usize] as i64) + i) as usize] as i64", "}", "",
          "fn scan_len(txsz: i64) -> i64 {", "    return SCAN_LEN_T[txsz as usize] as i64", "}", "",
          "// qidx -> dc/ac step; bd_idx = (bit_depth - 8) >> 1",
          "fn dc_q(bd_idx: i64, q: i64) -> i64 {", "    return DCQ[(bd_idx * 256 + q) as usize] as i64", "}", "",
          "fn ac_q(bd_idx: i64, q: i64) -> i64 {", "    return ACQ[(bd_idx * 256 + q) as usize] as i64", "}", ""]
    open(sys.argv[2], "w").write("\n".join(o))

main()
