"""tools/av1/gen_cdfs.py <entropymode.c> <token_cdfs.h> <out.fi> -- the AV1 default CDF tables as Firn data.

Source: libaom (BSD-2-Clause + AOM patent license), av1/common/entropymode.c and av1/common/token_cdfs.h.
Output layout (AV1 spec 8.2.6 form, NOT libaom's inverse form): every CDF is N ascending 15 bit values ending in 32768,
followed by one adaptation counter slot (0).  So a CDF of N symbols takes N + 1 cells.
  AV1_CDF_MODE   : all tables of entropymode.c, back to back
  AV1_CDF_COEF   : the coefficient tables of token_cdfs.h for ONE quantizer context each (4 contexts, selected by base_q_idx)
Per table the generator also writes  const C_<NAME>: usize = <offset>  (+ C_<NAME>_N symbols, _LEAVES = number of CDFs).
For the coefficient tables the offset is relative to the start of the selected quantizer slice.
"""
import re, sys

def strip_comments(s):
    s = re.sub(r"/\*.*?\*/", "", s, flags=re.S)
    return re.sub(r"//[^\n]*", "", s)

def num(x):
    x = x.strip()
    assert re.fullmatch(r"[0-9 *+-]+", x), x
    return int(eval(x))

def tables(src):
    src = strip_comments(src)
    out = []
    for m in re.finditer(r"static\s+const\s+aom_cdf_prob\s+(\w+)\s*((?:\[[^\]]*\]\s*)+)=\s*\{", src):
        name = m.group(1)
        i = m.end()
        depth = 1
        j = i
        while depth:
            c = src[j]
            depth += (c == "{") - (c == "}")
            j += 1
        body = src[m.end() - 1:j]
        leaves = []
        for lm in re.finditer(r"AOM_CDF(\d+)\(([^)]*)\)", body):
            n = int(lm.group(1))
            v = [num(x) for x in lm.group(2).replace("\n", " ").split(",") if x.strip()]
            assert len(v) == n - 1, (name, n, v)
            leaves.append(v + [32768])
        # the number of cells the declaration promises must match what was parsed (catches zero filled tails)
        assert leaves, name
        nsym = {len(l) for l in leaves}
        out.append((name, leaves, nsym))
    return out

def emit_array(label, ty, vals):
    lines = ["static %s: [%s; %d] = [" % (label, ty, len(vals))]
    for k in range(0, len(vals), 16):
        lines.append("    " + ", ".join(str(x) for x in vals[k:k + 16]) + ",")
    lines.append("]")
    return "\n".join(lines)

def main():
    modes = tables(open(sys.argv[1]).read())
    coefs = tables(open(sys.argv[2]).read())
    o = []
    o.append("// SPDX-License-Identifier: GPL-2.0-only")
    o.append("// lib/av1/avif_cdf.fi -- GENERATED by tools/av1/gen_cdfs.py from libaom's entropymode.c and token_cdfs.h")
    o.append("// (BSD-2-Clause + Alliance for Open Media Patent License 1.0, used under the GPL-2.0). DO NOT EDIT.")
    o.append("// AV1 default CDFs in spec form: N ascending values ending in 32768, then one counter cell (0). See the generator.")
    o.append("")
    o.append("export { cdf_mode, cdf_mode_addr, cdf_coef, cdf_coef_addr, CDF_MODE_LEN, CDF_COEF_LEN, CDF_COEF_QSTRIDE }")
    consts = []
    mode_cells = []
    names = []
    for name, leaves, nsym in modes:
        if len(nsym) != 1:
            # mixed symbol counts inside one table (e.g. per-size ext tx sets): keep, record each leaf stride separately
            sys.stderr.write("note: %s has mixed symbol counts %s\n" % (name, sorted(nsym)))
        n = max(nsym)
        base = len(mode_cells)
        for l in leaves:
            mode_cells.extend(l + [0] + [0] * (n - len(l)))   # padded to the table's widest CDF like libaom
        nm = re.sub(r"^(av1_)?default_", "", name).upper()
        nm = re.sub(r"_CDFS?$", "", nm)
        consts.append((nm, base, n, len(leaves), len(nsym) == 1))
    coef_cells_q = []
    qlen = None
    cconsts = []
    for name, leaves, nsym in coefs:
        assert len(nsym) == 1, name
        n = max(nsym)
        assert len(leaves) % 4 == 0, name
        per = len(leaves) // 4
        nm = re.sub(r"^(av1_)?default_", "", name).upper()
        nm = re.sub(r"_CDFS?$", "", nm)
        cconsts.append((nm, per, n))
    # coefficient layout: for q in 0..3: [table0 slice q][table1 slice q] ...  -> contiguous slice per q
    slices = [[] for _ in range(4)]
    offs = {}
    pos = 0
    for name, leaves, nsym in coefs:
        n = max(nsym)
        per = len(leaves) // 4
        nm = re.sub(r"^(av1_)?default_", "", name).upper()
        nm = re.sub(r"_CDFS?$", "", nm)
        offs[nm] = (pos, n, per)
        for q in range(4):
            for l in leaves[q * per:(q + 1) * per]:
                slices[q].extend(l + [0])
        pos = len(slices[0])
    assert all(len(s) == len(slices[0]) for s in slices)
    qs = len(slices[0])
    coef_cells = [x for s in slices for x in s]
    o.append("")
    o.append("const CDF_MODE_LEN: usize = %d" % len(mode_cells))
    o.append("const CDF_COEF_LEN: usize = %d" % len(coef_cells))
    o.append("const CDF_COEF_QSTRIDE: usize = %d" % qs)
    o.append("")
    for nm, base, n, cnt, uniform in consts:
        o.append("export { M_%s, M_%s_N, M_%s_LEAVES }" % (nm, nm, nm))
        o.append("const M_%s: usize = %d" % (nm, base))
        o.append("const M_%s_N: usize = %d" % (nm, n))
        o.append("const M_%s_LEAVES: usize = %d" % (nm, cnt))
    for nm, (pos, n, per) in offs.items():
        o.append("export { K_%s, K_%s_N, K_%s_LEAVES }" % (nm, nm, nm))
        o.append("const K_%s: usize = %d" % (nm, pos))
        o.append("const K_%s_N: usize = %d" % (nm, n))
        o.append("const K_%s_LEAVES: usize = %d" % (nm, per))
    o.append("")
    o.append(emit_array("AV1_CDF_MODE", "u16", mode_cells))
    o.append("")
    o.append(emit_array("AV1_CDF_COEF", "u16", coef_cells))
    o.append("")
    o.append("fn cdf_mode(i: usize) -> u16 {\n    return AV1_CDF_MODE[i]\n}\n")
    o.append("fn cdf_mode_addr() -> u64 {\n    return (&AV1_CDF_MODE[0]) as u64\n}\n")
    o.append("fn cdf_coef(i: usize) -> u16 {\n    return AV1_CDF_COEF[i]\n}\n")
    o.append("fn cdf_coef_addr() -> u64 {\n    return (&AV1_CDF_COEF[0]) as u64\n}")
    open(sys.argv[3], "w").write("\n".join(o) + "\n")
    print("mode tables %d (%d cells), coef tables %d (%d cells per q, %d total)" % (len(consts), len(mode_cells), len(offs), qs, len(coef_cells)))

if __name__ == "__main__":
    main()
