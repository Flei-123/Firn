#!/bin/sh
set -e
root=$(cd "$(dirname "$0")/../.." && pwd)
table="$root/tools/csalias/table.txt"
methods="$root/compiler/src/method_modules.rs"
rs="$root/compiler/src/csalias_table.rs"
fi_out="$root/lib/firnc1/csalias_table.fi"
rows=$(mktemp)
trap 'rm -f "$rows"' EXIT
{
    awk '{ print $1, $2, ($3 == "bare" ? 1 : 0) + ($3 == "prop" ? 2 : 0), ($3 == "bare" && $4 != "" ? $4 "." : "-") }' "$table"
    grep -oE '"[a-z_0-9]+",' "$methods" | tr -d '",' | LC_ALL=C sort -u | while read -r name; do
        pascal=$(echo "$name" | sed -E 's/(^|_)([a-z0-9])/\U\2/g')
        echo "$pascal $name 0 -"
    done
} | awk '!seen[$1]++' | LC_ALL=C sort > "$rows"
count=$(wc -l < "$rows")
{
    echo "// SPDX-License-Identifier: MPL-2.0"
    echo "// Generated by tools/csalias/gen.sh from tools/csalias/table.txt. Do not edit."
    echo "pub(crate) const ALIASES: [(&str, &str, &str, u8); $count] = ["
    while read -r pascal target flags prefix; do
        [ "$prefix" = "-" ] && prefix=""
        echo "    (\"$pascal\", \"$target\", \"$prefix\", $flags),"
    done < "$rows"
    echo "];"
} > "$rs"
{
    echo "// SPDX-License-Identifier: MPL-2.0"
    echo "// Generated by tools/csalias/gen.sh from tools/csalias/table.txt. Do not edit."
    echo "export { CS_COUNT, cs_index, cs_target, cs_prefix, cs_flags }"
    echo "import derive_decl"
    echo
    echo "const CS_COUNT: usize = $count"
    echo
    echo "fn cs_index(src: u64, s: usize, e: usize) -> i32 {"
    i=0
    while read -r pascal target flags prefix; do
        echo "    if derive_decl.dv_eq_lit(src, s, e, \"$pascal\") { return $i }"
        i=$((i + 1))
    done < "$rows"
    echo "    return 0 - 1"
    echo "}"
    echo
    echo "fn cs_target(i: i32) -> str {"
    i=0
    while read -r pascal target flags prefix; do
        echo "    if i == $i { return \"$target\" }"
        i=$((i + 1))
    done < "$rows"
    echo "    return \"\""
    echo "}"
    echo
    echo "fn cs_prefix(i: i32) -> str {"
    i=0
    while read -r pascal target flags prefix; do
        [ "$prefix" = "-" ] && prefix=""
        [ -n "$prefix" ] && echo "    if i == $i { return \"$prefix\" }"
        i=$((i + 1))
    done < "$rows"
    echo "    return \"\""
    echo "}"
    echo
    echo "fn cs_flags(i: i32) -> u32 {"
    i=0
    while read -r pascal target flags prefix; do
        [ "$flags" != "0" ] && echo "    if i == $i { return $flags as u32 }"
        i=$((i + 1))
    done < "$rows"
    echo "    return 0 as u32"
    echo "}"
} > "$fi_out"
