#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."
export NOGCTEXT_TARGET="${1:-lib/firnc1/nogctext.fi}"
python3 - <<'PYEOF'
import os
target = os.environ.get('NOGCTEXT_TARGET', 'lib/firnc1/nogctext.fi')
src = open('lib/gc/nogc.fi', 'rb').read()
words = []
for i in range(0, len(src), 8):
    words.append(int.from_bytes(src[i:i + 8].ljust(8, b'\0'), 'little'))
out = []
out.append('// SPDX-License-Identifier: MPL-2.0')
out.append('// lib/firnc1/nogctext.fi -- GENERATED by tools/gen_nogctext.sh from')
out.append('// lib/gc/nogc.fi. DO NOT EDIT BY HAND.')
out.append('import rt')
out.append('')
out.append('export { NOGCTEXT_N, nogctext_write }')
out.append('')
out.append('const NOGCTEXT_N: u64 = %d' % len(src))
out.append('')
out.append('static NOGCTEXT_WORDS: [u64; %d] = [' % len(words))
for i in range(0, len(words), 10):
    out.append('    ' + ' '.join(str(x) + ',' for x in words[i:i + 10]))
out.append(']')
out.append('')
out.append('fn nogctext_write(b: *mut rt.Buf) {')
out.append('    var written: u64 = 0')
out.append('    var i: usize = 0')
out.append('    while i < %d {' % len(words))
out.append('        let v: u64 = NOGCTEXT_WORDS[i]')
out.append('        var k: u64 = 0')
out.append('        while k < 8 {')
out.append('            if written >= NOGCTEXT_N {')
out.append('                return')
out.append('            }')
out.append('            rt.buf_push(b, ((v >> (k * 8)) & 255) as u8)')
out.append('            written = written + 1')
out.append('            k = k + 1')
out.append('        }')
out.append('        i = i + 1')
out.append('    }')
out.append('}')
open(target, 'w').write('\n'.join(out) + '\n')
PYEOF
