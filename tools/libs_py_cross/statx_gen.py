# Generates tests/4525_std_statx.fi from CPython 3.11 `statistics` (inputs/results as IEEE bit patterns).
import statistics as S, struct, random, math
R = random.Random(2026)
def bits(x): return struct.unpack('<Q', struct.pack('<d', x))[0]
def U(x): return "0x%016x" % bits(x)
NV = 35  # values per dataset
xs_all = []; ys_all = []; lens = []; exp = []; mm_lens = []; mm_data = []
nsets = 0
while nsets < 80:
    n = R.randint(2, 20)
    scale = R.choice([8, 8, 100, 1000])
    x = [(R.randint(0, 40) + 1) / 8.0 * (1 if scale == 8 else scale / 8.0) for _ in range(n)]
    y = [(R.randint(0, 40) + 1) / 8.0 + (0.5 * xi if R.random() < 0.5 else 0.0) for xi in x]
    try:
        row = [S.median_low(x), S.median_high(x), S.fmean(x), S.geometric_mean(x), S.harmonic_mean(x),
               S.mode(x), float(len(S.multimode(x))),
               S.covariance(x, y), S.correlation(x, y)]
        lr = S.linear_regression(x, y)
        row += [lr.slope, lr.intercept]
        for nn in (4, 10):
            row += S.quantiles(x, n=nn) if nn == 4 else []
        q4e = S.quantiles(x, n=4); q4i = S.quantiles(x, n=4, method='inclusive')
        q10e = S.quantiles(x, n=10); q10i = S.quantiles(x, n=10, method='inclusive')
    except (S.StatisticsError, ZeroDivisionError):
        continue
    row = row[:11] + q4e + q4i + q10e + q10i
    assert len(row) == NV, len(row)
    exp.extend(row)
    xs_all.extend(x); ys_all.extend(y); lens.append(n)
    mm = S.multimode(x); mm_lens.append(len(mm)); mm_data.extend(mm)
    nsets += 1
o = []
o.append("// expect_exit: 0")
o.append("// tests/4525_std_statx.fi -- std.statx against CPython 3.11 `statistics` (80 data sets).")
o.append("// GENERATED by tools/libs_py_cross/statx_gen.py: data and CPython results as IEEE bit patterns.")
o.append("// median_low/high, mode, multimode, quantiles: bit-exact; means, covariance, correlation and")
o.append("// regression (Python uses exact fractions, we use compensated sums): relative 1e-11.")
o.append("import std.io\nimport std.rt\nimport std.vec\nimport std.math\nimport std.statx\nimport std.testkit\n")
o.append('''fn f(b: u64) -> f64 { return math.math_f64(b) }
fn close(got: f64, want: f64) -> bool {
    if math.is_nan(want) { return math.is_nan(got) }
    let d: f64 = math.fabs(got - want)
    return d <= 1e-11 * math.fabs(want) + 1e-14
}
fn same(got: f64, want: f64) -> bool { return math.math_bits(got) == math.math_bits(want) }
''')
o.append("fn lens() -> [u64; %d] { return [%s] }" % (len(lens), ", ".join(map(str, lens))))
o.append("fn xs() -> [u64; %d] { return [%s] }" % (len(xs_all), ", ".join(U(v) for v in xs_all)))
o.append("fn ys() -> [u64; %d] { return [%s] }" % (len(ys_all), ", ".join(U(v) for v in ys_all)))
o.append("fn want() -> [u64; %d] { return [%s] }" % (len(exp), ", ".join(U(v) for v in exp)))
o.append("fn mm_lens() -> [u64; %d] { return [%s] }" % (len(mm_lens), ", ".join(map(str, mm_lens))))
o.append("fn mm_data() -> [u64; %d] { return [%s] }" % (len(mm_data), ", ".join(U(v) for v in mm_data)))
o.append('''fn main() -> i32 {
    if !gc_init() { return 1 }
    let ln: [u64; %(N)d] = lens()
    let xd: [u64; %(NX)d] = xs()
    let yd: [u64; %(NX)d] = ys()
    let w: [u64; %(NW)d] = want()
    let ml: [u64; %(N)d] = mm_lens()
    let md: [u64; %(NM)d] = mm_data()
    var pos: usize = 0
    var mpos: usize = 0
    var bad_exact: usize = 0
    var bad_close: usize = 0
    var bad_mm: usize = 0
    for c in 0..(%(N)d as usize) {
        var x: Vec[f64] = vec_new[f64]()
        var y: Vec[f64] = vec_new[f64]()
        for k in 0..(ln[c] as usize) {
            vec_push[f64](&x, f(xd[pos + k]))
            vec_push[f64](&y, f(yd[pos + k]))
        }
        pos = pos + (ln[c] as usize)
        let b: usize = c * %(NV)d
        if !same(statx.median_low(&x), f(w[b])) { bad_exact = bad_exact + 1 }
        if !same(statx.median_high(&x), f(w[b + 1])) { bad_exact = bad_exact + 1 }
        if !close(statx.fmean(&x), f(w[b + 2])) { bad_close = bad_close + 1 }
        if !close(statx.geometric_mean(&x), f(w[b + 3])) { bad_close = bad_close + 1 }
        if !close(statx.harmonic_mean(&x), f(w[b + 4])) { bad_close = bad_close + 1 }
        var md1: f64 = 0.0
        stat_mode[f64](&x, &md1)
        if !same(md1, f(w[b + 5])) { bad_exact = bad_exact + 1 }
        var mm: Vec[f64] = vec_new[f64]()
        stat_multimode[f64](&x, &mm)
        if (vec_len[f64](&mm) as u64) != ml[c] { bad_mm = bad_mm + 1 }
        else {
            for k in 0..(ml[c] as usize) {
                if !same(*vec_elem_ptr[f64](&mm, k), f(md[mpos + k])) { bad_mm = bad_mm + 1 }
            }
        }
        mpos = mpos + (ml[c] as usize)
        vec_free[f64](&mm)
        if !close(statx.covariance(&x, &y), f(w[b + 7])) { bad_close = bad_close + 1 }
        if !close(statx.correlation(&x, &y), f(w[b + 8])) { bad_close = bad_close + 1 }
        var sl: f64 = 0.0
        var ic: f64 = 0.0
        if !statx.linear_regression(&x, &y, &sl, &ic) { bad_close = bad_close + 1 }
        if !close(sl, f(w[b + 9])) { bad_close = bad_close + 1 }
        if !close(ic, f(w[b + 10])) { bad_close = bad_close + 1 }
        var q: Vec[f64] = vec_new[f64]()
        statx.quantiles(&x, 4, false, &q)
        statx.quantiles(&x, 4, true, &q)
        statx.quantiles(&x, 10, false, &q)
        statx.quantiles(&x, 10, true, &q)
        if vec_len[f64](&q) != 24 { bad_exact = bad_exact + 1 }
        else {
            for k in 0..(24 as usize) {
                if !same(*vec_elem_ptr[f64](&q, k), f(w[b + 11 + k])) { bad_exact = bad_exact + 1 }
            }
        }
        vec_free[f64](&q)
        vec_free[f64](&x)
        vec_free[f64](&y)
    }
    testkit.check(bad_exact == 0, "median_low/high, mode, quantiles bit-exact (80 sets)")
    testkit.check(bad_mm == 0, "multimode (80 sets)")
    testkit.check(bad_close == 0, "fmean/geometric/harmonic/covariance/correlation/regression within 1e-11")
    return testkit.finish()
}
''' % dict(N=len(lens), NX=len(xs_all), NW=len(exp), NM=max(1, len(mm_data)), NV=NV))
open("tests/4525_std_statx.fi", "w").write("\n".join(o) + "\n")
print("sets", len(lens), "values", len(exp))
