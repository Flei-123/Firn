# Generates tests/4521_std_mathx.fi (float cases with CPython `math` results as
# bit patterns) and prints the integer checksums used by tests/4522.
import math, struct, random, sys
random.seed(20261019)
def bits(x): return struct.unpack('<Q', struct.pack('<d', x))[0]
def U(x): return "0x%016x" % bits(x)
R = random.Random(11)
def rng(lo, hi, n):
    return [R.uniform(lo, hi) for _ in range(n)]
def logr(lo, hi, n):
    return [math.exp(R.uniform(math.log(lo), math.log(hi))) * R.choice([-1, 1]) for _ in range(n)]
cases = {}   # name -> (kind, inputs(list of tuples), expected(list))
def add(name, kind, ins, fn):
    exp = []
    keep = []
    for t in ins:
        try:
            v = fn(*t)
        except (ValueError, OverflowError, ZeroDivisionError):
            continue
        keep.append(t); exp.append(v)
    cases[name] = (kind, keep, exp)
add("asin", "tr", [(x,) for x in rng(-1, 1, 36) + [-1.0, 0.0, 1.0, 1e-9, -1e-12, 0.5]], math.asin)
add("acos", "tr", [(x,) for x in rng(-1, 1, 36) + [-1.0, 0.0, 1.0, 1e-9, 0.5, 0.999999]], math.acos)
add("sinh", "tr", [(x,) for x in rng(-30, 30, 30) + [0.0, 1e-9, -1e-5, 0.3, -0.4, 50.0, 700.0]], math.sinh)
add("cosh", "tr", [(x,) for x in rng(-30, 30, 30) + [0.0, 1e-9, 0.3, 50.0, 700.0, -700.0]], math.cosh)
add("tanh", "tr", [(x,) for x in rng(-8, 8, 30) + [0.0, 1e-9, -1e-5, 0.3, 40.0, -40.0]], math.tanh)
add("asinh", "tr", [(x,) for x in rng(-1e5, 1e5, 20) + rng(-2, 2, 15) + [0.0, 1e-9, -1e-7, 1e200]], math.asinh)
add("acosh", "tr", [(x,) for x in rng(1, 1e5, 20) + rng(1, 3, 15) + [1.0000001, 1e200]], math.acosh)
add("atanh", "tr", [(x,) for x in rng(-0.999, 0.999, 36) + [0.0, 1e-9, -1e-7, 0.999999, 0.5]], math.atanh)
add("expm1", "tr", [(x,) for x in rng(-20, 20, 30) + rng(-0.6, 0.6, 14) + [0.0, 1e-12, -1e-9, 0.5, -0.5]], math.expm1)
add("log1p", "tr", [(x,) for x in rng(-0.99, 5, 25) + logr(1e-12, 1e6, 15) + [0.0, 1e-12, -1e-9, 0.25, -0.25]], math.log1p)
add("cbrt", "tr", [(x,) for x in logr(1e-20, 1e20, 40) + [27.0, -8.0, 0.0, 1.0, 1e-300]], math.cbrt)
add("erf", "tr", [(x,) for x in rng(-5, 5, 40) + [0.0, 1e-9, 0.5, -0.5, 2.9999, 3.0001, 6.5]], math.erf)
add("erfc", "tr", [(x,) for x in rng(-3, 6, 40) + [0.0, 2.0, 5.0, 10.0, 26.0, -1e-9]], math.erfc)
add("gamma", "tr", [(x,) for x in rng(0.1, 20, 25) + rng(-8, 0, 12) if abs(x - round(x)) > 0.01]
    + [(float(k),) for k in range(1, 24)] + [(0.5,), (1.5,), (-0.5,), (100.5,), (170.5,)], math.gamma)
add("lgamma", "tr", [(x,) for x in rng(0.1, 200, 25) + rng(-8, 0, 10) if abs(x - round(x)) > 0.01 and abs(x - 1) > 0.05 and abs(x - 2) > 0.05]
    + [(0.5,), (10.0,), (100.0,), (1e5,), (-0.5,)], math.lgamma)
# exact ones
def pairs_f(n):
    out = []
    for _ in range(n):
        out.append((R.uniform(-50, 50), R.uniform(-50, 50)))
    out += [(3.0, -0.0), (-3.0, 0.0), (0.0, -1.0), (1.5, math.inf), (math.inf, -2.0), (1.0, math.nan), (-0.0, 5.0)]
    return out
add("copysign", "ex", pairs_f(30), math.copysign)
rem = pairs_f(40) + [(7.0, 2.0), (5.0, 2.0), (2.5, 1.0), (3.5, 1.0), (-2.5, 1.0), (-3.5, 1.0), (0.5, 1.0), (1.5, 1.0),
                      (1e300, 3.0), (1e-300, 7.0), (6.0, 3.0), (-6.0, 3.0), (9.0, 6.0), (4.5, 3.0), (7.5, 5.0), (10.0, 4.0)]
add("remainder", "ex", rem, math.remainder)
add("fmod_py", "ex", pairs_f(30) + [(-7.5, 2.0), (7.5, -2.0), (-7.5, -2.0), (6.0, -3.0), (-6.0, 3.0)], lambda x, y: x % y)
add("degrees", "ex", [(x,) for x in rng(-10, 10, 20) + [0.0, math.pi, 1.0]], math.degrees)
add("radians", "ex", [(x,) for x in rng(-720, 720, 20) + [0.0, 180.0, 1.0]], math.radians)
cl = []
for _ in range(40):
    a = R.uniform(-100, 100)
    cl.append((a, a * (1 + R.choice([0, 1e-12, 1e-10, 1e-8, 1e-6])), 1e-9, 0.0))
cl += [(0.0, 1e-12, 1e-9, 0.0), (0.0, 1e-12, 1e-9, 1e-10), (1.0, 1.0, 0.0, 0.0), (math.inf, math.inf, 1e-9, 0.0),
       (math.inf, 1.0, 1e-9, 0.0), (math.nan, math.nan, 1e-9, 0.0), (1.0, 1.0000001, 1e-9, 0.0), (1.0, 1.0000001, 1e-6, 0.0)]
add("isclose", "bool", cl, lambda a, b, r, t: math.isclose(a, b, rel_tol=r, abs_tol=t))

out = []
out.append("// expect_exit: 0")
out.append("// tests/4521_std_mathx.fi -- std.mathx float functions against CPython 3.11 `math`.")
out.append("// GENERATED by tools/libs_py_cross/mathx_gen.py: inputs and CPython results as IEEE bit patterns.")
out.append("// copysign/remainder/fmod_py/degrees/radians/isclose: bit-exact. The others: relative 1e-11")
out.append("// (std.math exp/ln/atan2 are series approximations, see tests/805).")
out.append("import std.rt\nimport std.vec\nimport std.math\nimport std.mathx\nimport std.testkit\n")
out.append('''fn f(b: u64) -> f64 { return math.math_f64(b) }
fn close(got: f64, want: f64) -> bool {
    if math.is_nan(want) { return math.is_nan(got) }
    if math.is_infinite(want) { return got == want }
    let d: f64 = math.fabs(got - want)
    return d <= 1e-11 * math.fabs(want) || d == 0.0
}
fn same(got: f64, want: f64) -> bool {
    if math.is_nan(want) { return math.is_nan(got) }
    return math.math_bits(got) == math.math_bits(want)
}
''')
body = []
for name, (kind, ins, exp) in cases.items():
    n = len(ins)
    arity = len(ins[0])
    for k in range(arity):
        out.append("fn %s_in%d() -> [u64; %d] { return [%s] }" % (name, k, n, ", ".join(U(t[k]) for t in ins)))
    if kind == "bool":
        out.append("fn %s_want() -> [u64; %d] { return [%s] }" % (name, n, ", ".join("1" if e else "0" for e in exp)))
    else:
        out.append("fn %s_want() -> [u64; %d] { return [%s] }" % (name, n, ", ".join(U(e) for e in exp)))
    call = {
        "asin": "mathx.asin(f(a0[i]))", "acos": "mathx.acos(f(a0[i]))", "sinh": "mathx.sinh(f(a0[i]))",
        "cosh": "mathx.cosh(f(a0[i]))", "tanh": "mathx.tanh(f(a0[i]))", "asinh": "mathx.asinh(f(a0[i]))",
        "acosh": "mathx.acosh(f(a0[i]))", "atanh": "mathx.atanh(f(a0[i]))", "expm1": "mathx.expm1(f(a0[i]))",
        "log1p": "mathx.log1p(f(a0[i]))", "cbrt": "mathx.cbrt(f(a0[i]))", "erf": "mathx.erf(f(a0[i]))",
        "erfc": "mathx.erfc(f(a0[i]))", "gamma": "mathx.gamma(f(a0[i]))", "lgamma": "mathx.lgamma(f(a0[i]))",
        "copysign": "mathx.copysign(f(a0[i]), f(a1[i]))", "remainder": "mathx.remainder(f(a0[i]), f(a1[i]))",
        "fmod_py": "mathx.fmod_py(f(a0[i]), f(a1[i]))", "degrees": "mathx.degrees(f(a0[i]))",
        "radians": "mathx.radians(f(a0[i]))",
        "isclose": "mathx.isclose(f(a0[i]), f(a1[i]), f(a2[i]), f(a3[i]))",
    }[name]
    b = ["fn run_%s() {" % name]
    for k in range(arity):
        b.append("    let a%d: [u64; %d] = %s_in%d()" % (k, n, name, k))
    b.append("    let w: [u64; %d] = %s_want()" % (n, name))
    b.append("    var bad: usize = 0")
    b.append("    for i in 0..(%d as usize) {" % n)
    if kind == "bool":
        b.append("        var got: u64 = 0")
        b.append("        if %s { got = 1 }" % call)
        b.append("        if got != w[i] { bad = bad + 1 }")
    else:
        cmp = "close" if kind == "tr" else "same"
        b.append("        if !%s(%s, f(w[i])) { bad = bad + 1 }" % (cmp, call))
    b.append("    }")
    b.append('    testkit.check(bad == 0, "%s (%d cases)")' % (name, n))
    b.append("}\n")
    out.extend(b)
    body.append("    run_%s()" % name)

# fsum: vectors flattened
fs = []
lens = []
exp = []
for _ in range(120):
    n = R.randint(0, 14)
    mode = R.randint(0, 3)
    if mode == 0: v = [R.uniform(-1, 1) for _ in range(n)]
    elif mode == 1: v = [R.uniform(-1, 1) * 10 ** R.randint(-30, 30) for _ in range(n)]
    elif mode == 2: v = [0.1] * n
    else:
        v = [R.uniform(-1, 1) * 10 ** R.randint(-5, 5) for _ in range(n)]
        v += [-x for x in v]; R.shuffle(v)
    lens.append(len(v)); fs.extend(v); exp.append(math.fsum(v))
extra = [[1e100, 1.0, -1e100, 1.0], [0.1, 0.2, 0.3], [1e16, 1.0, 1.0], [2.0**53, 1.0, 1.0, 1.0], [math.inf, 1.0], [math.inf, -math.inf], []]
for v in extra:
    lens.append(len(v)); fs.extend(v)
    exp.append(math.fsum(v) if not (math.inf in v and -math.inf in v) else math.nan)
out.append("fn fsum_lens() -> [u64; %d] { return [%s] }" % (len(lens), ", ".join(str(x) for x in lens)))
out.append("fn fsum_data() -> [u64; %d] { return [%s] }" % (len(fs), ", ".join(U(x) for x in fs)))
out.append("fn fsum_want() -> [u64; %d] { return [%s] }" % (len(exp), ", ".join(U(x) for x in exp)))
out.append('''fn run_fsum() {
    let lens: [u64; %d] = fsum_lens()
    let data: [u64; %d] = fsum_data()
    let want: [u64; %d] = fsum_want()
    var pos: usize = 0
    var bad: usize = 0
    for c in 0..(%d as usize) {
        var v: Vec[f64] = vec_new[f64]()
        for k in 0..(lens[c] as usize) {
            vec_push[f64](&v, f(data[pos + k]))
        }
        pos = pos + (lens[c] as usize)
        if !same(mathx.fsum(&v), f(want[c])) { bad = bad + 1 }
        vec_free[f64](&v)
    }
    testkit.check(bad == 0, "fsum (%d vectors)")
}
''' % (len(lens), len(fs), len(exp), len(lens), len(lens)))
body.append("    run_fsum()")
out.append("fn main() -> i32 {\n    if !gc_init() { return 1 }")
out.extend(body)
out.append("    return testkit.finish()\n}")
open("tests/4521_std_mathx.fi", "w").write("\n".join(out) + "\n")
print("cases", {k: len(v[1]) for k, v in cases.items()}, "fsum", len(lens))
