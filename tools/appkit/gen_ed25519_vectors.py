# Generates the vector block of tests/2050_ed25519.fi with Python's `cryptography`
# (an Ed25519 nobody here wrote). RFC 8032 section 7.1 TEST 1-3 are asserted
# against the literals of the RFC, so the generator itself is checked.
#   python3 tools/appkit/gen_ed25519_vectors.py > /tmp/vectors.fi
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from cryptography.hazmat.primitives import serialization

L = 2 ** 252 + 27742317777372353535851937790883648493


def vec(seed_hex, msg):
    sk = Ed25519PrivateKey.from_private_bytes(bytes.fromhex(seed_hex))
    pk = sk.public_key().public_bytes(serialization.Encoding.Raw,
                                      serialization.PublicFormat.Raw)
    return pk.hex(), sk.sign(msg).hex()


