print('// generated by tools/appkit/gen_ed25519_vectors.py -- do not edit by hand')
print('const NVEC: usize = %d' % len(cases))
for n, (seed, msg) in enumerate(cases):
    pk, sig = vec(seed, msg)
    if seed in RFC:
        assert (pk, sig) == RFC[seed], 'RFC 8032 literal mismatch'
    print('const V%d_SEED: str = "%s"' % (n, seed))
    print('const V%d_PUB: str = "%s"' % (n, pk))
    print('const V%d_MSG: str = "%s"' % (n, msg.hex()))
    print('const V%d_SIG: str = "%s"' % (n, sig))
pk, sig = vec(*cases[0])
s = int.from_bytes(bytes.fromhex(sig)[32:], 'little')
mal = bytes.fromhex(sig)[:32] + (s + L).to_bytes(32, 'little')
print('// the signature of V0 with S replaced by S+L: same point equation, not canonical')
print('const MALLEABLE_SIG: str = "%s"' % mal.hex())
