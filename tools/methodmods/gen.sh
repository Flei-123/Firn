#!/bin/sh
set -e
root=$(cd "$(dirname "$0")/../.." && pwd)
modules="nummethods strmethods"
extra_strmethods="trim trim_left trim_right contains starts_with ends_with is_empty length find"
rs="$root/compiler/src/method_modules.rs"
fi_out="$root/lib/firnc1/method_modules.fi"
names_of() {
    mod=$1
    own=$(grep -oE 'fn [a-z_0-9]+\((\*|\*mut )?self' "$root/lib/std/$mod.fi" | sed -E 's/fn ([a-z_0-9]+)\(.*/\1/')
    eval "extra=\$extra_$mod"
    printf '%s\n' $own $extra | LC_ALL=C sort -u
}
count=$(echo $modules | wc -w)
{
    echo "// SPDX-License-Identifier: MPL-2.0"
    echo "// Generated by tools/methodmods/gen.sh from lib/std. Do not edit."
    echo "pub(crate) const METHOD_MODULES: [(&str, &[&str]); $count] = ["
    for m in $modules; do
        echo "    (\"$m\", &["
        for n in $(names_of $m); do echo "        \"$n\","; done
        echo "    ]),"
    done
    echo "];"
} > "$rs"
{
    echo "// SPDX-License-Identifier: MPL-2.0"
    echo "// Generated by tools/methodmods/gen.sh from lib/std. Do not edit."
    echo "export { MM_COUNT, mm_bits }"
    echo "import derive_decl"
    echo
    echo "const MM_COUNT: usize = $count"
    echo
    echo "fn mm_bits(src: u64, s: usize, e: usize) -> u32 {"
    bit=1
    for m in $modules; do
        for n in $(names_of $m); do
            echo "    if derive_decl.dv_eq_lit(src, s, e, \"$n\") { return $bit as u32 }"
        done
        bit=$((bit * 2))
    done
    echo "    return 0 as u32"
    echo "}"
} > "$fi_out"
sh "$root/tools/csalias/gen.sh"
