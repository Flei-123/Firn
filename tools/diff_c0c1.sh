#!/usr/bin/env bash
# tools/diff_c0c1.sh -- DIFFERENTIAL TEST firnc0 (Rust) against firnc1 (Firn).
#
# The same program is built with both compilers and compared:
#   kind "run"  every build level (dev, dev-fast, release-safe, release-fast): build result,
#               standard output, exit code, first stderr line (panic message) of the
#               produced binaries; plus the same program across the levels (the checked
#               levels must agree; release-fast too unless the header says
#               `// levels: fast_differs`, because it wraps instead of checking).
#   kind "neg"  both compilers must REJECT the program, with the same error class
#               (parse / type). firnc1 prints no details, so the class is the yardstick.
#
# Corpus: tests/diff/*.fi, generated by tools/diff_c0c1_gen.py (fixed seed).
# Headers: `// diff: run|neg`, `// levels: same|fast_differs`.
#
# Verdicts: SAME, DEVIATION (hard: counted, exit 1), KNOWN (listed in tools/diff_c0c1.known),
#           UNSUPPORTED (firnc1 answers 3/4/5/6 = not core language yet; not a deviation).
#
# Environment: DIFF_DIR (corpus), DIFF_ONLY (name filter), DIFF_JOBS (parallel shards, default 4),
#              DIFF_VERBOSE=1, FIRNC, FIRNC1, DIFF_A64=1 (extra: firnc0 aarch64 under qemu for the
#              "abi_"/"ovf_"/"wrap_" programs against firnc0 x86-64).
# Heavy use: /root/jarvis/bin/heavy bash tools/diff_c0c1.sh
set -uo pipefail
cd "$(dirname "$0")/.."
export FIRNLIB="$(pwd)/lib"

FIRNC=${FIRNC:-compiler/target/release/firnc}
FC1=${FIRNC1:-./.firnc1}
DIR=${DIFF_DIR:-tests/diff}
KNOWN=tools/diff_c0c1.known
LEVELS="dev dev-fast release-safe release-fast"

level_flag() {
    case "$1" in
        dev) echo "--no-opt";;
        *) echo "--opt-level=$1";;
    esac
}

if [ -z "${DIFF_SHARD:-}" ]; then
    WORK=$(mktemp -d)
    trap 'rm -rf "$WORK"' EXIT
    rebuild=0
    [ -x "$FC1" ] || rebuild=1
    if [ -x "$FC1" ]; then
        [ "$FIRNC" -nt "$FC1" ] && rebuild=1
        while IFS= read -r q; do
            [ "$q" -nt "$FC1" ] && { rebuild=1; break; }
        done < <(find bin lib -name '*.fi' -not -type l)
    fi
    if [ "$rebuild" -eq 1 ]; then
        "$FIRNC" bin/firnc1.fi -o "$WORK/firnc1.new" || { echo "cannot build firnc1"; exit 2; }
        mv -f "$WORK/firnc1.new" "$FC1" || exit 2
    fi
    n=${DIFF_JOBS:-4}
    pids=""
    k=0
    while [ "$k" -lt "$n" ]; do
        DIFF_SHARD="$k/$n" DIFF_WORK="$WORK/s$k" bash "$0" > "$WORK/out.$k" 2>&1 &
        pids="$pids $!"
        k=$((k+1))
    done
    wait $pids
    cat "$WORK"/out.* | grep -v '^@@' | sort
    awk '/^@@/ {c[$2]+=$3} END {
        printf "programs: %d  (run %d, neg %d)\n", c["programs"], c["run"], c["neg"]
        printf "builds compared: %d  runs compared: %d\n", c["builds"], c["runs"]
        printf "SAME programs: %d\n", c["same"]
        printf "DEVIATIONS: %d\n", c["deviation"]
        printf "KNOWN: %d\n", c["known"]
        printf "SOFT (panic text / message class): %d\n", c["soft"]
        printf "UNSUPPORTED by firnc1: %d\n", c["unsupported"]
        printf "OPT-LEVEL deviations: %d\n", c["optdev"]
        if (c["a64"] > 0) printf "aarch64 checked: %d  differences: %d\n", c["a64"], c["a64dev"]
    }' <(cat "$WORK"/out.* | grep '^@@')
    dev=$(cat "$WORK"/out.* | grep '^@@ deviation ' | awk '{s+=$3} END {print s+0}')
    [ "$dev" -eq 0 ]
    exit $?
fi

SK=${DIFF_SHARD%/*}
SN=${DIFF_SHARD#*/}
W=$DIFF_WORK
mkdir -p "$W"

declare -A cnt
inc() { cnt[$1]=$(( ${cnt[$1]:-0} + ${2:-1} )); }

is_known() {
    [ -f "$KNOWN" ] && grep -q "^$1\b" "$KNOWN"
}

dev() {
    local f=$1 what=$2
    local b
    b=$(basename "$f" .fi)
    if is_known "$b"; then
        inc known
        echo "KNOWN      $b: $what"
    else
        inc deviation
        echo "DEVIATION  $b: $what"
    fi
    has_dev=1
}

first_line() { head -n 1 "$1" 2>/dev/null | tr -d '\r'; }

err_class0() {
    if "$FIRNC" --emit=ast-canon "$1" > /dev/null 2>&1; then echo type; else echo parse; fi
}
err_class1() {
    if [ ! -s "$1" ]; then echo parse; return; fi
    if grep -q 'type checker reported' "$1"; then echo type
    else echo parse; fi
}

do_neg() {
    local f=$1 b
    b=$(basename "$f" .fi)
    "$FIRNC" -o "$W/n0.bin" "$f" > "$W/n0.out" 2>&1
    local r0=$?
    "$FC1" "$f" -o "$W/n1.bin" > "$W/n1.out" 2>&1
    local r1=$?
    inc builds
    if grep -qE 'panicked at|RUST_BACKTRACE' "$W/n0.out"; then dev "$f" "firnc0 crashed (Rust panic)"; return; fi
    case "$r1" in 3|4|5|6) inc unsupported; echo "UNSUPPORTED $b: firnc1 rc=$r1"; has_dev=2; return;; esac
    if [ "$r0" -ne 0 ] && [ "$r1" -ne 0 ]; then
        local c0 c1
        c0=$(err_class0 "$f")
        c1=$(err_class1 "$W/n1.out")
        if [ "$c0" != "$c1" ]; then
            inc soft
            echo "SOFT       $b: error class firnc0=$c0 firnc1=$c1 ($(first_line "$W/n0.out"))"
        fi
    elif [ "$r0" -ne 0 ] && [ "$r1" -eq 0 ]; then
        dev "$f" "firnc0 rejects ($(first_line "$W/n0.out")), firnc1 ACCEPTS"
    elif [ "$r0" -eq 0 ] && [ "$r1" -ne 0 ]; then
        dev "$f" "firnc0 accepts, firnc1 rejects ($(first_line "$W/n1.out"))"
    else
        dev "$f" "both ACCEPT a program that has to be rejected"
    fi
}

run_one() {
    timeout 20 "$1" < /dev/null > "$2" 2> "$3"
    echo $?
}

do_run() {
    local f=$1 b lv fl
    b=$(basename "$f" .fi)
    local levels
    levels=$(sed -n 's|^// levels: ||p' "$f" | head -n 1)
    [ -z "$levels" ] && levels=same
    local checked=""
    for lv in $LEVELS; do
        fl=$(level_flag "$lv")
        rm -f "$W/b0" "$W/b1"
        "$FIRNC" $fl -o "$W/b0" "$f" > "$W/b0.log" 2>&1
        local r0=$?
        "$FC1" $fl "$f" -o "$W/b1" > "$W/b1.log" 2>&1
        local r1=$?
        inc builds
        case "$r1" in 3|4|5|6) inc unsupported; echo "UNSUPPORTED $b [$lv]: firnc1 rc=$r1"; has_dev=2; return;; esac
        if [ "$r0" -ne "$r1" ]; then
            dev "$f" "[$lv] build result firnc0=$r0 firnc1=$r1 ($(first_line "$W/b0.log") | $(first_line "$W/b1.log"))"
            return
        fi
        [ "$r0" -ne 0 ] && continue
        local e0 e1
        e0=$(run_one "$W/b0" "$W/o0.$lv" "$W/e0.$lv")
        e1=$(run_one "$W/b1" "$W/o1.$lv" "$W/e1.$lv")
        inc runs
        if [ "$e0" != "$e1" ] || ! cmp -s "$W/o0.$lv" "$W/o1.$lv"; then
            dev "$f" "[$lv] run firnc0 exit=$e0 firnc1 exit=$e1 out: $(head -c 60 "$W/o0.$lv" | tr '\n' ' ') | $(head -c 60 "$W/o1.$lv" | tr '\n' ' ')"
            return
        fi
        local m0 m1
        m0=$(first_line "$W/e0.$lv" | sed 's/ at [^ ]*:[0-9]*:[0-9]*.*//')
        m1=$(first_line "$W/e1.$lv" | sed 's/ at [^ ]*:[0-9]*:[0-9]*.*//')
        if [ "$m0" != "$m1" ]; then
            inc soft
            echo "SOFT       $b [$lv]: panic text firnc0='$m0' firnc1='$m1'"
        fi
        echo "$e0" > "$W/x0.$lv"
    done
    local a=dev
    for lv in dev-fast release-safe release-fast; do
        [ "$lv" = release-fast ] && [ "$levels" = fast_differs ] && continue
        if [ "$(cat "$W/x0.$a")" != "$(cat "$W/x0.$lv")" ] || ! cmp -s "$W/o0.$a" "$W/o0.$lv"; then
            inc optdev
            dev "$f" "opt levels differ in firnc0: $a exit=$(cat "$W/x0.$a") vs $lv exit=$(cat "$W/x0.$lv")"
            return
        fi
        if ! cmp -s "$W/o1.$a" "$W/o1.$lv"; then
            inc optdev
            dev "$f" "opt levels differ in firnc1: $a vs $lv"
            return
        fi
    done
    if [ -n "${DIFF_A64:-}" ]; then
        case "$b" in abi_*|ovf_*|wrap_*|cast_*|shift_*|layout_*)
            if "$FIRNC" --target=aarch64-linux --opt-level=release-safe -o "$W/ba" "$f" > /dev/null 2>&1; then
                timeout 60 qemu-aarch64 "$W/ba" < /dev/null > "$W/oa" 2> /dev/null
                ea=$?
                inc a64
                if [ "$ea" != "$(cat "$W/x0.release-safe")" ] || ! cmp -s "$W/oa" "$W/o0.release-safe"; then
                    inc a64dev
                    dev "$f" "aarch64 (qemu) exit=$ea differs from x86-64"
                    return
                fi
            fi;;
        esac
    fi
}

idx=0
for f in "$DIR"/*.fi; do
    [ -f "$f" ] || continue
    idx=$((idx+1))
    [ $(( (idx - 1) % SN )) -eq "$SK" ] || continue
    case "$f" in *"${DIFF_ONLY:-}"*) ;; *) continue;; esac
    if head -n 3 "$f" | grep -q '^// firnc1_skip'; then continue; fi
    inc programs
    has_dev=0
    kind=$(sed -n 's|^// diff: ||p' "$f" | head -n 1)
    if [ "$kind" = neg ]; then
        inc neg
        do_neg "$f"
    else
        inc run
        do_run "$f"
    fi
    [ "$has_dev" -eq 0 ] && inc same
    [ -n "${DIFF_VERBOSE:-}" ] && echo "done $(basename "$f")"
done

for k in "${!cnt[@]}"; do echo "@@ $k ${cnt[$k]}"; done
exit 0
