import sys
from fontTools.cffLib import cffStandardStrings
from fontTools.encodings.StandardEncoding import StandardEncoding

strings = list(cffStandardStrings)
index = {n: i for i, n in enumerate(strings)}
blob = "|".join(strings) + "|"
std_sids = [index.get(n, 0) if n != ".notdef" else 0 for n in StandardEncoding]
lines = []
lines.append("// SPDX-License-Identifier: MPL-2.0")
lines.append("// CFF standard strings and the standard encoding (generated by tools/docview/gen_cff_data.py).")
lines.append("")
lines.append("import rt.rt")
lines.append("")
lines.append("export {")
lines.append("    cff_std_string_copy, cff_std_sid_for_name, cff_std_encoding_sid,")
lines.append("}")
lines.append("")
lines.append("fn cff_std_string_copy(sid: usize, out: *mut u8, cap: usize) -> usize {")
lines.append("    var t: [u8; %d] = \"%s\"" % (len(blob), blob))
lines.append("    var idx: usize = 0")
lines.append("    var s: usize = 0")
lines.append("    var i: usize = 0")
lines.append("    while i < %d {" % len(blob))
lines.append("        if t[i] == 124 as u8 {")
lines.append("            if idx == sid {")
lines.append("                var k: usize = 0")
lines.append("                while k < i - s && k < cap {")
lines.append("                    *((out as u64 + k as u64) as *mut u8) = t[s + k]")
lines.append("                    k = k + 1")
lines.append("                }")
lines.append("                return k")
lines.append("            }")
lines.append("            idx = idx + 1")
lines.append("            s = i + 1")
lines.append("        }")
lines.append("        i = i + 1")
lines.append("    }")
lines.append("    return 0")
lines.append("}")
lines.append("")
lines.append("fn cff_std_sid_for_name(p: u64, n: usize) -> i32 {")
lines.append("    var t: [u8; %d] = \"%s\"" % (len(blob), blob))
lines.append("    var idx: i32 = 0")
lines.append("    var s: usize = 0")
lines.append("    var i: usize = 0")
lines.append("    while i < %d {" % len(blob))
lines.append("        if t[i] == 124 as u8 {")
lines.append("            if i - s == n {")
lines.append("                var same: bool = true")
lines.append("                var k: usize = 0")
lines.append("                while k < n {")
lines.append("                    if t[s + k] != rt.ld8(p, k) {")
lines.append("                        same = false")
lines.append("                    }")
lines.append("                    k = k + 1")
lines.append("                }")
lines.append("                if same {")
lines.append("                    return idx")
lines.append("                }")
lines.append("            }")
lines.append("            idx = idx + 1")
lines.append("            s = i + 1")
lines.append("        }")
lines.append("        i = i + 1")
lines.append("    }")
lines.append("    return -1")
lines.append("}")
lines.append("")
lines.append("#[no_gc]")
lines.append("fn cff_std_encoding_sid(code: usize) -> u32 {")
rows = []
for i in range(0, 256, 16):
    rows.append("        " + ", ".join(str(v) for v in std_sids[i:i+16]))
lines.append("    var t: [u32; 256] = [")
lines.append(",\n".join(rows) + "]")
lines.append("    if code > 255 {")
lines.append("        return 0 as u32")
lines.append("    }")
lines.append("    return t[code]")
lines.append("}")
open(sys.argv[1], "w").write("\n".join(lines) + "\n")
