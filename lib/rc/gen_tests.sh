#!/usr/bin/env bash
# Produces the Rc test programs out of the ONE implementation
# (tests/modules/rc.fi, symlink lib/rc/rc.fi) and the test bodies in
# lib/rc/parts/.
#
# Why copy them together at all instead of 'import modules.rc'?
# Stage 0 does not resolve generic templates across module boundaries: neither
# 'rc.RefCount[T]' in type position nor 'rc.rc_new[T](..)' in a call
# can be compiled ("expected '=' after the name ..." resp. "only
# direct function names can be called"). lib/str already uses exactly the
# same solution (tools/strlib/expand.py): the library stands
# once in the tree and is put into the test programs verbatim.
# Run with:  bash lib/rc/gen_tests.sh [--check]
set -euo pipefail
cd "$(dirname "$0")/../.."
MOD=tests/modules/rc.fi
OUT=.
CHECK=0
if [ "${1:-}" = "--check" ]; then
    CHECK=1
    OUT=$(mktemp -d)
    trap 'rm -rf "$OUT"' EXIT
    mkdir -p "$OUT/tests/neg"
fi
STALE=0

generate() {                 # $1 = body, $2 = target file
    local body="$1" dest="$2"
    {
        grep -m1 '^// expect' "$body"
        echo "// GENERATED by lib/rc/gen_tests.sh: line 1 and the body from"
        echo "// $body, with tests/modules/rc.fi VERBATIM in between."
        grep -v '^// SPDX-License-Identifier:' "$MOD"
        grep -v -e '^// SPDX-License-Identifier:' -e '^// expect' "$body"
    } > "$OUT/$dest"
    if [ "$CHECK" = 1 ] && ! cmp -s "$OUT/$dest" "$dest"; then
        echo "out of date: $dest"
        STALE=$((STALE + 1))
    fi
}

for r in lib/rc/parts/5*.fi; do
    generate "$r" "tests/$(basename "$r")"
    [ "$CHECK" = 1 ] || echo "  tests/$(basename "$r")"
done
for r in lib/rc/parts/neg_*.fi; do
    n=$(basename "$r"); n=${n#neg_}
    generate "$r" "tests/neg/$n"
    [ "$CHECK" = 1 ] || echo "  tests/neg/$n"
done

# Round 47: the same mechanism for `Arc[T]` (lib/rc/arc.fi).
MOD=lib/rc/arc.fi
for r in lib/rc/parts/83*.fi; do
    generate "$r" "tests/$(basename "$r")"
    [ "$CHECK" = 1 ] || echo "  tests/$(basename "$r")"
done
for r in lib/rc/parts/negarc_*.fi; do
    n=$(basename "$r"); n=${n#negarc_}
    generate "$r" "tests/neg/$n"
    [ "$CHECK" = 1 ] || echo "  tests/neg/$n"
done

if [ "$CHECK" = 1 ]; then
    echo "gen_tests.sh: $STALE files out of date"
    [ "$STALE" = 0 ]
fi
